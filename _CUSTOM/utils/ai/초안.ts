import { shallowRef } from 'vue'

/**
 * 챗봇이 지목한 행동에 딸려 가는 초안 한 벌.
 *
 * "오늘 3~4시에 점검한다고 공지해"의 **뒷부분**이 담기는 자리다. 앞부분(어느 게시판이냐)은
 * 계획의 `검색어s`·`대상id`가 이미 처리하지만, 쓸 내용은 조회 계획이 담을 수 있는 성격이 아니다.
 *
 * 왜 인자로 안 넘기고 모듈 스코프인가 — 행동 버튼은 `i행동버튼.onClick: () => any`라 인자를 받지 않는다.
 * 시그니처를 바꾸면 이 값을 쓸 일이 영영 없는 `do*` 수십 개가 전부 영향을 받는다. 대신 `화면문맥`과
 * 같은 방식으로 **대화 밖 한 겹**을 두고 필요한 쪽만 집어 간다.
 * 화면문맥이 "누구에게"를 넘기는 자리라면, 여기는 "무슨 내용으로"를 넘기는 자리다.
 *
 * 실행이 아니라 초안이라는 게 요점이다. 이걸 집어 가는 쪽(글쓰기 화면)은 폼을 채울 뿐이고,
 * 등록은 언제나 사용자가 누른다 — `do*` 전체에 걸린 규칙과 같다.
 */
export interface i행동초안 {
  제목: string
  /** 편집기가 먹는 **md**. 평문으로 들어오면 `set행동초안`이 문단으로 가른다. */
  본문: string
}

/** shallow: 담기는 건 평범한 객체 한 개다. 깊은 반응형으로 쌀 이유가 없다. */
const 초안 = shallowRef<i행동초안 | null>(null)

/**
 * 버튼을 **누르는 순간** 얹는다. 계획이 나오자마자 얹어두면 안 된다 —
 * 누르지 않고 넘어간 초안이 남아 있다가, 나중에 사용자가 손으로 연 글쓰기 화면에 튀어나온다.
 * 그건 사용자가 시킨 적 없는 일이다.
 */
export function set행동초안(v: Partial<i행동초안> | null | undefined) {
  if (import.meta.server) return
  const 제목 = String(v?.제목 ?? '').trim()
  const 본문 = 초안본문md(v?.본문)
  초안.value = 제목 || 본문 ? { 제목, 본문 } : null
}

/**
 * 꺼내면서 지운다. 한 번 쓰이고 사라지는 게 이 값의 수명 전부다 —
 * 남겨두면 "저번에 안 누른 초안"이 언제 튀어나올지 아무도 모른다.
 */
export function take행동초안(): i행동초안 | null {
  const v = 초안.value
  초안.value = null
  return v
}

/**
 * 초안 본문 → 편집기가 먹는 md.
 *
 * ## 왜 HTML 정제가 사라졌나 (2026-09-07)
 *
 * 게시글 본문이 md 로 저장되면서(`Input본문`) 모델에게도 md 로 쓰라고 시킨다. 그래서 예전처럼
 * 「허용 태그 화이트리스트」를 들고 있을 이유가 없어졌다 — **태그는 하나도 안 통과시킨다.**
 * 화이트리스트는 「이 태그들은 살려야 한다」는 요구가 있을 때만 필요한 물건이고, 지금 요구는
 * 반대다. 그래서 코드가 목록이 아니라 규칙 하나로 줄었다.
 *
 * **그래도 태그를 훑는다.** 프롬프트는 지침이지 보장이 아니라는 사정은 그대로다 — 모델이 옛날
 * 버릇으로 `<p>` 를 뱉으면 md 에서는 그게 글자로 보이거나(파서가 인라인 HTML 로 흘리면) 그대로
 * 실린다. 아는 태그는 md 로 옮기고(`<strong>` → `**`), 모르는 태그는 껍데기만 벗긴다.
 *
 * **DOMParser 를 쓰지 않는다.** 브라우저에만 있는 물건이라 서버·테스트에서는 다른 길로 새고,
 * 그 길에서는 애써 만든 목록·강조가 통째로 평문이 된다(실측). 어디서 돌든 같은 결과여야
 * "편집기에 들어가기 전 모습"을 한 군데서 이야기할 수 있다.
 *
 * 정규식의 한계는 알고 있다. 여기 들어오는 건 우리가 부른 모델의 출력이고, 저장 전에 사람이
 * 편집기에서 한 번 보며, 편집기의 스키마(`m/Editor/_/확장.ts`)가 모르는 것을 한 겹 더 떨군다.
 * 임의의 외부 입력을 렌더하는 자리라면 이걸로 부족하다 — 그럴 땐 파서를 붙여야 한다.
 */
export function 초안본문md(v: unknown): string {
  const s = String(v ?? '').trim()
  if (!s) return ''
  return is태그있음(s) ? 태그걷기(s) : 정돈(s)
}

/**
 * `<태그>` 가 실제로 있는가.
 *
 * **md 의 자동링크(`<https://…>`)를 태그로 읽으면 안 된다.** 저장 경로가 주소만 있는 링크를
 * 그 꼴로 뱉으므로(`문서에서md`) 링크 한 줄짜리 초안이 통째로 태그 취급을 받는다.
 * 태그 이름은 글자·숫자로만 이어지다 공백이나 `>` 로 닫힌다 — `https:` 의 `:` 가 그 자리를 못 넘는다.
 */
const 태그찾기 = /<(\/?)([a-z][a-z0-9]*)((?:\s[^>]*)?)\/?>/gi
const is태그있음 = (s: string) => new RegExp(태그찾기.source, 'i').test(s)

/** 짝을 포함해 통째로 버린다. 껍데기만 벗기면 안쪽 코드가 글자로 남는다. */
const 통째로버릴태그 = /^(?:script|style|iframe|object|embed|template|noscript)$/i

/** `javascript:` 류를 막는다. 상대경로·앵커·http(s)·mailto·tel만 통과. */
function 안전한href(v: string): boolean {
  const s = v.trim().toLowerCase()
  if (!s) return false
  if (/^(https?:|mailto:|tel:)/.test(s)) return true
  return /^[/#?]/.test(s)
}

const href찾기 = /\bhref\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i

/** 아는 태그의 md 짝. 여는 쪽과 닫는 쪽이 같은 것(강조)과 다른 것(제목·목록)이 섞여 있다. */
const 인라인짝: Record<string, string> = {
  strong: '**', b: '**', em: '*', i: '*', s: '~~', del: '~~', code: '`'
}
const 여는줄: Record<string, string> = {
  h1: '# ', h2: '## ', h3: '### ', h4: '#### ', h5: '##### ', h6: '###### ',
  li: '- ', blockquote: '> ', hr: '---'
}
/**
 * 경계가 **빈 줄**인 태그와 **줄바꿈 하나**인 태그.
 *
 * md 에서 이 둘은 다른 뜻이다 — 목록 항목 사이에 빈 줄이 들어가면 「느슨한 목록」이 되어
 * 항목마다 문단 간격이 붙는다. `<li>` 를 문단으로 취급하면 그 꼴이 된다.
 */
const 문단태그 = /^(?:p|div|h[1-6]|ul|ol|blockquote|pre|table|thead|tbody|hr)$/i
const 줄태그 = /^(?:li|tr|br)$/i
/** 표의 칸. 줄을 갈지는 않지만 붙여 놓으면 글자가 엉킨다. */
const 칸태그 = /^(?:td|th)$/i

/**
 * 태그가 섞인 초안 → md.
 *
 * **표는 못 옮긴다.** `<table>` 을 GFM 표로 되돌리려면 행·칸을 세어 헤더 구분줄을 만들어야 하는데,
 * 그건 정규식 한 줄이 아니라 파서다. 지금은 칸을 줄로 풀어 **글자만** 남긴다 —
 * 모델에게 md 표(`| a | b |`)를 쓰라고 시켰으니 이 길로 오는 표는 이미 예외다.
 */
function 태그걷기(html: string): string {
  const 나온 = html
    .replace(/<(script|style|iframe|object|embed|template|noscript)\b[\s\S]*?<\/\1\s*>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(태그찾기, (_전체, 닫기: string, 이름: string, 속성: string) => {
      const 태그 = 이름.toLowerCase()
      if (통째로버릴태그.test(태그)) return ''

      if (태그 === 'a') {
        if (닫기) return '](@@href@@)'
        const m = href찾기.exec(속성)
        const href = m?.[1] ?? m?.[2] ?? m?.[3] ?? ''
        return href && 안전한href(href) ? `[@@${href.trim()}@@` : ''
      }

      const 짝 = 인라인짝[태그]
      if (짝) return 짝

      if (칸태그.test(태그)) return ' '
      // 닫는 쪽이 줄을 긋는 건 문단뿐이다. `</li>` 가 그으면 다음 `<li>` 의 줄과 겹쳐 빈 줄이 되고,
      // 그 빈 줄이 md 에서 「느슨한 목록」을 만든다.
      if (닫기) return 문단태그.test(태그) ? '\n\n' : ''
      const 줄바꿈 = 문단태그.test(태그) ? '\n\n' : 줄태그.test(태그) ? '\n' : ''
      return 줄바꿈 + (여는줄[태그] ?? '')
    })
    // 링크는 여는 쪽에서 주소를 알고 닫는 쪽에서 자리를 안다. 짝을 맞춘 뒤에야 주소가 제자리로 간다.
    .replace(/\[@@([^@]*)@@([\s\S]*?)\]\(@@href@@\)/g, (_전체, 주소: string, 글자: string) =>
      `[${글자.trim() || 주소}](${주소})`)
    .replace(/\[@@[^@]*@@|\]\(@@href@@\)/g, '')

  // 태그가 있던 자리에 남은 공백. 여기 들여쓰기는 뜻이 없으니(중첩 목록을 만들지 않는다) 턴다.
  return 정돈(엔티티풀기(나온).replace(/[ \t]{2,}/g, ' ').replace(/^[ \t]+/gm, ''))
}

/*
  **태그가 없으면 손대지 않는다.** 예전에는 평문을 문단으로 감쌌는데(`<p>`), md 에서 같은 일을
  하려면 줄바꿈마다 빈 줄을 넣어야 하고 그러면 **md 로 잘 써 온 초안이 부서진다** —
  `- 하나 / - 둘` 사이에 빈 줄이 끼면 느슨한 목록이 되고, 표는 헤더 구분줄과 갈라진다.
  모델에게 md 로 쓰라고 시킨 이상 태그 없는 입력은 md 로 보는 게 맞다. 평문도 md 로 치면
  그냥 한 문단이고, 문장 중간 줄바꿈이 공백으로 접히는 건 저장 경로가 어차피 하는 일이다
  (`m/Editor/md.vue` 「실측」의 첫째 항목).
*/

/**
 * **`&lt;` 는 `<` 가 아니라 `\<` 로 푼다.** 여기서 그냥 `<` 로 풀면 `&lt;script&gt;` 가
 * 태그로 되살아나는데, 태그를 걷는 일은 이미 끝난 뒤라 아무도 다시 안 본다.
 * `\<` 는 md 가 「보이는 꺾쇠」로 읽으므로 글자는 그대로 남고 태그는 못 연다.
 */
function 엔티티풀기(s: string) {
  return s
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '\\<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, '\'')
    // `&amp;`는 마지막에 — 먼저 풀면 `&amp;lt;`가 `<`로 두 번 풀린다.
    .replace(/&amp;/g, '&')
}

/** 빈 줄이 셋 이상 겹치면 문단 사이가 벌어져 보인다. 둘로 줄이고 줄 끝 공백을 턴다. */
function 정돈(s: string) {
  return s.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trim()
}

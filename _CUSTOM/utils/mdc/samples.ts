/**
 * 본문 샘플 문서. **어휘가 아니라 「이 어휘로 뭘 어디까지 쓸 수 있나」를 보여주는 자리다.**
 *
 * 셋을 고른 기준은 **읽는 사람이 다르다**는 것이다. 같은 블록도 독자가 달라지면 쓰임이 달라진다 —
 * 운영자 매뉴얼의 `경고`는 "네가 실수하면 못 되돌린다"이고, 공지의 `경고`는 "돈이 안 돌아온다"다.
 *
 * | | 읽는 사람 | 어디에 |
 * |---|---|---|
 * | `운영매뉴얼` | 내부 스태프 | 자료(`resources`) — 도우미가 발췌해 답하는 문서 |
 * | `공지글` | 회원 | 게시판(`member-posts`) |
 * | `과정소개` | 방문자 | 페이지 본문 |
 *
 * **나중에 도우미의 few-shot 재료가 될 자리이기도 하다.** 사전(`blocks.ts`)이 규칙을 말하고
 * 여기가 완성된 글을 보여준다 — 규칙만으로는 "블록을 언제 **안** 쓰는지"가 안 전해진다.
 * 그래서 세 편 다 **블록을 아껴 썼다.** 대부분이 그냥 문단·목록·표다. 모래밭이 사전의
 * "한 글에 한둘이면 충분하다"를 어기면 그 문장이 거짓말이 된다.
 *
 * **이 셋이 `docs` 표의 시드다**(2026-09-06, `~models/v2/model문서`). 2026-09-07부터는 **사본이 아니라
 * 파생이다** — `model문서.seed.ts` 가 이 파일의 `본문샘플s` 를 읽어 dto 로 옮긴다. 옮기지 않는 건
 * `설명` 하나뿐이다(그건 「견본으로서 이 글이 무엇을 보이나」라 문서의 `요약`과 다른 말이다).
 * 그래도 **이미 부어진 행은 안 바뀐다** — 시드는 목록이 비어 있을 때만 돌고
 * (`BaseModels2.do초기데이터`), 부어진 행은 **처음 저장할 때 원문이 정규화되고 그 뒤로는 고정이다**
 * (`m/Editor/md.vue` 「실측」). 여기 md 를 고쳤는데 `/v2/docs` 가 그대로면 그건 그 두 가지지 버그가 아니다.
 * 모래밭이 보는 건 늘 이 파일 쪽이다.
 *
 * **2026-09-05: 사진을 넣었다.** 처음 세 편에는 사진이 한 장도 없었는데, 그게 어휘가 아니라
 * **글이 거짓말을 하고 있던 것**이었다 — 학원 과정 소개에 사진이 없을 리가 없다. 세어 보니
 * 0장이었고, 그래서 `photo`·`columns` 어댑터가 필요하다는 게 드러났다.
 * 어휘가 부족한지 판단하는 방법은 목록을 남과 비교하는 게 아니라 **쓸 글을 실제로 써 보는 것**이다.
 *
 * **2026-09-07: 표에 열 정렬을 주고, `영상`·`목록`을 처음 넣었다.** 같은 방법으로 다시 세어 본 것이다.
 *
 * - **열 정렬**(`|:---:|`)이 세 편의 표 어디에도 없었다. 본문 편집기가 그 손잡이를 갖게 된 날
 *   (`mEditor` 툴바의 `정렬`, 표 안에서는 열 전체에 걸린다) **저장된 md 로 그 왕복을 지나는 글이
 *   한 편도 없다**는 게 드러났다. 없는 건 안 깨진다 — 깨지는 걸 보려면 시드가 그걸 써야 한다.
 *   그래서 짧은 값이 서는 열만 가운데(`상태`·`주차`·`준비물`), 날짜 열은 오른쪽으로 줬다.
 *   **꾸미려고 준 게 아니라 그 열의 값이 실제로 그렇게 읽히는 자리만** 골랐다.
 * - **`영상`·`목록`은 사전에는 있는데 쓰인 적이 없었다.** 어휘 13개 중 이 둘만 그랬다.
 *   방문자용 과정 소개에 수업 맛보기 영상이 없을 리 없고, 개강 공지에 열리는 반 목록이 없을 리 없다 —
 *   사진 때와 같은 종류의 거짓말이다. 한 편에 하나씩만 넣었다(사전의 「한 글에 여럿 넣지 않는다」).
 *   `목록`은 앱을 읽어 그리는 유일한 어휘라, 이 한 줄이 **본문 안에서 앱 데이터가 그려지는 유일한 자리**이기도 하다.
 */


/**
 * `::` 어휘 사전. **이 파일 하나가 네 곳을 먹인다** — 렌더 화이트리스트 · 도우미 프롬프트 ·
 * 저작 툴바(`m/Editor/Editor.vue`) · 편집기 스키마(`m/Editor/_/확장.ts`).
 * 두 벌이 되는 순간 도우미가 없는 블록을 지어낸다.
 *
 * `aiV2/sources.ts`가 표에 대해 하는 일을 본문에 대고 하는 것이다. 그래서 규율도 같은 걸 따른다
 * (근거는 전부 실측이다. 추측이 아니라 겪은 것들이다).
 *
 * 1. **어휘에는 라벨을 적고, 이름으로 되돌리는 건 앱이 한다.**
 *    칸을 키로 열었더니 도우미가 사람 말 그대로 `이름`을 냈고 그 턴이 통째로 죽었다.
 *    여기서는 그 처방이 **강제**이기도 하다 — `remark-mdc`의 이름 토크나이저가 ASCII만 받아서
 *    `::경고`는 파싱 자체가 안 된다(글자로 남는다). 그래서 md 에는 `이름`, 사람과 프롬프트에는 `라벨`.
 * 2. **`쓸때`가 고르는 유일한 근거다.** 소스의 `설명`과 같은 자리. "무엇인가"가 아니라
 *    **"언제 고르나 + 옆 것과 어떻게 갈리나"**를 적는다. 모양이 비슷한 블록끼리 경계를 안 적으면
 *    LLM은 무작위로 고른다.
 * 3. **무엇을 하지 말지 적는다.** "표로 붙인다"고 알려줬더니 자기가 마크다운 표를 그렸다.
 *    그래서 `금지`가 설명의 일부다.
 * 4. **선택지는 enum 으로 닫는다.** 열어두면 통째로 빼먹거나 사전 밖 값을 낸다.
 *    (도우미 수정 폼이 자유 문자라 필터에 안 걸리는 행이 생기는 미결 §4-3과 같은 병이다 —
 *    여기서는 처음부터 닫을 수 있다.)
 * 5. **별명으로 사람 말을 받아준다.** 아래 `별명` 배열이 그것이다 — `알림`을 `참고`·`안내`로도 받는다.
 *    **어휘를 늘리는 게 아니라 말을 앱이 받아준다.**
 * 6. **능력과 권한은 다르다.** 렌더러가 아는 블록(@nuxt/ui prose 세트는 20개가 넘는다)과
 *    도우미에게 연 블록은 다른 목록이다. 이 파일은 **권한** 쪽이다.
 *
 * ## 왜 우리가 만든 컴포넌트가 없나
 *
 * `@nuxt/ui` 4가 prose 컴포넌트로 이미 다 갖고 있고(`note`·`tip`·`warning`·`caution`·`card`·
 * `card-group`·`steps`·`tabs`·`badge`·`kbd`…), **전부 시맨틱 토큰을 쓴다**(`border-default`·
 * `bg-primary/10`·`border-info/25`). 즉 이미 테마 축을 탄다. 새로 만들 이유가 없다.
 * 없는 것(영상 등)만 나중에 어댑터로 붙인다.
 */


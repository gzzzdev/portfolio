import type { i소스V2, i항목V2 } from './source'
import type { PlanV2 } from './plan'
import type { i화면대상 } from '../ai/화면문맥'

/** `대상id`로 지목할 수 있는 행 하나. 대화가 남긴 것과 화면이 준 것이 같은 자격으로 들어온다. */
interface i지목후보V2 {
  /**
   * 계획이 지목하는 키 = `소스:id`. **id만으로는 행이 안 닫힌다** — 테이블마다 id가 1001부터라
   * `animals`의 1002와 `vegetables`의 1002가 같은 값이고, 실측에서 지목이 다른 표의 행으로 풀렸다.
   * enum은 닫혀 있었지만 닫힌 값이 두 행을 가리킨 것이다.
   */
  키: string
  /** 실제 행 id. 계획을 실행할 때는 접두어를 떼고 이걸 쓴다. */
  id: string
  source: string
  label: string
}

/**
 * 지목 후보를 모은다. 직전 턴(대화가 남긴 것)과 화면 선택(대화 밖에서 온 것)은 동등한 근거다 —
 * 한 목록으로 합쳐야 enum 하나로 닫히고 소스를 되찾는 경로도 하나가 된다.
 */
function 지목후보s(직전s: i항목V2[], 화면: i화면대상 | null): i지목후보V2[] {
  const 키of = (source: string, id: string) => `${source}:${id}`

  const 후보: i지목후보V2[] = 직전s
    .filter(x => x.id)
    .map(x => ({ 키: 키of(x.source, x.id), id: x.id, source: x.source, label: x.label }))

  if (화면?.id && !후보.some(x => x.키 === 키of(화면.source, 화면.id)))
    후보.push({ 키: 키of(화면.source, 화면.id), id: 화면.id, source: 화면.source, label: 화면.label })

  return 후보
}

/**
 * 지금 화면에 걸려 있는 조회 조건. 도우미가 기억한 게 아니라 **주소에서 읽은 사실**이다
 * (`i소스V2.쿼리필터s`가 `?f_<축>=`를 되돌린 값).
 */
export interface i화면조건V2 {
  /** 그 조건이 걸린 소스 키. 계획이 다른 소스를 고르면 통째로 버린다. */
  source: string
  /** `"축=값"` 목록. */
  필터s: string[]
}

/**
 * 앞 턴의 필터를 **축 단위로** 이어받는다. 이번 턴이 말한 축은 새 값이 이기고,
 * 말하지 않은 축은 화면에 걸린 채로 남는다 — 「여름 채소」 다음의 「그중에 뿌리」가 여기서 1건이 된다.
 *
 * **번역 호출에는 아무것도 안 붙는다.** 무엇이 걸려 있는지는 앱이 아는 사실이라 프롬프트로
 * 부탁할 일이 아니다. 병합 지점을 여기 하나로 두는 이유: `계획실행V2`(건수)와 `조회쿼리`(주소)가
 * **같은 `필터s`를** 읽는다. 두 군데서 따로 합치면 도우미가 세는 수와 화면이 보여주는 수가 갈린다.
 *
 * 이어받는 턴은 조회(`count`·`list`)뿐이다. 그리고 **이번 턴이 축을 하나도 안 말했으면
 * 이어받지 않는다** = 조건 풀기(「채소 전체 보여줘」). 반대로 두면 사용자가 자기가 안 건 조건에 갇힌다.
 */
function 필터이어받기(plan: PlanV2, target: i소스V2, 화면조건: i화면조건V2 | null): PlanV2 {
  if (!화면조건 || 화면조건.source !== target.key) return plan
  if (plan.intent !== 'count' && plan.intent !== 'list') return plan

  const 이번s = plan.필터s ?? []
  if (!이번s.length) return plan

  const 축of = (조건: string) => {
    const s = String(조건 ?? '')
    const i = s.indexOf('=')
    return i < 0 ? s : s.slice(0, i)
  }
  const 말한축s = new Set(이번s.map(축of))
  const 이어받을s = 화면조건.필터s.filter(조건 => !말한축s.has(축of(조건)))

  return 이어받을s.length ? { ...plan, 필터s: [...이번s, ...이어받을s] } : plan
}

/**
 * 계획 호출의 responseSchema.
 *
 * `검색어`와 `intent`를 **required로 닫는 게 이 스키마의 전부다** — 선택 속성으로 두면 lite가
 * 통째로 빼먹는다. 지켜야 할 것을 문장으로 부탁하지 말고 스키마로 불가능하게 만든다.
 * `대상id`·`행동`은 **고를 게 있을 때만** 속성을 만든다. 자리가 없으면 지어낼 길도 없다.
 */
function 계획스키마V2(sources: i소스V2[], 후보s: i지목후보V2[], 행동s: string[], can생성: boolean, 수정필드s: string[], 필터s: string[], 정렬s: string[], 탭s: string[]) {
  const properties: Record<string, unknown> = {
    source: {
      type: 'string',
      enum: sources.map(s => s.key),
      description: '질문이 가리키는 소스의 key. 어느 쪽인지 단서가 없으면 첫 번째.'
    },
    검색어: {
      type: 'string',
      description: '찾을 이름의 일부. 조사·어미는 떼고 핵심어만. 전체를 보는 질문이면 빈 문자열.'
    },
    intent: { type: 'string', enum: ['count', 'list', 'act', 'select', ...(can생성 ? ['create'] : [])] }
  }

  // 축을 가진 소스가 하나도 없으면 자리를 안 만든다 — v2 장난감 표 대부분이 그렇다.
  // 자리가 있으면 lite 는 채우려 들고, 없는 축을 채우면 그 턴이 통째로 어긋난다.
  if (필터s.length)
    properties.필터s = {
      type: 'array',
      maxItems: 4,
      items: { type: 'string', enum: 필터s },
      description: '적용할 필터. 어휘의 "필터s:" 줄에 적힌 "축=값"을 그대로. 조건이 없으면 빈 배열.'
    }

  if (정렬s.length > 1)
    properties.정렬조건 = {
      type: 'string',
      enum: 정렬s,
      description: '사용자가 순서를 말했을 때만. 안 말했으면 비운다.'
    }

  // 만들 수 있는 소스가 하나도 없으면 이름 칸도 만들지 않는다. 자리가 없으면 지어낼 길도 없다.
  if (can생성) {
    properties.생성이름s = {
      type: 'array',
      maxItems: 10,
      items: { type: 'string' },
      description: 'intent="create"일 때 만들 항목의 이름들. 사용자가 말한 이름만 그대로. 안 말했으면 빈 배열.'
    }
    // 개수를 이름 배열과 나눠 두는 이유는 `PlanV2.생성개수` 주석에 있다 —
    // "3개"에 빈 문자열 셋을 시키면 lite 가 그 대신 이름을 지어낸다.
    properties.생성개수 = {
      type: 'integer',
      description: 'intent="create"일 때 만들 개수. 사용자가 수를 말했으면 그 수, 아니면 1.'
    }
  }

  // 묶음이 둘 이상인 소스가 하나도 없으면 자리를 안 만든다 — 필터 축과 같은 규율이다.
  if (탭s.length)
    properties.탭 = {
      type: 'string',
      enum: 탭s,
      description: '한 건을 열면서 그 행의 어느 묶음을 보자고 했을 때만("성격 보여줘"). 아니면 비운다.'
    }

  if (후보s.length)
    properties.대상id = {
      type: 'string',
      enum: 후보s.map(x => x.키),
      description: '지목할 행의 키. 목록에 적힌 "소스:id" 형태 그대로 옮겨라.'
    }

  if (행동s.length) {
    properties.행동 = { type: 'string', enum: 행동s }
    properties.행동값 = {
      type: 'string',
      description: '그 행동에 딸린 한 줄 값(남길 기록 내용, 바꿔 넣을 새 값 등). 사용자가 말한 것만 그대로. 안 말했으면 빈 문자열.'
    }
    // 고칠 칸은 **닫힌 목록에서 고르게** 한다 — 형식을 지침으로 부탁하면 샌다.
    // 쌍의 **배열**인 이유: 모델의 필수 칸이 둘이면 한 칸짜리 축은 말을 반쪽만 싣는다.
    // 상한은 lite 가 배열을 만나면 채우려 들기 때문이다 — 자리는 열되 넓히지 않는다.
    if (수정필드s.length)
      properties.수정s = {
        type: 'array',
        maxItems: 5,
        description: '행동="do수정"일 때 고칠 칸과 새 값의 쌍들. 수정 턴이 아니면 빈 배열.',
        items: {
          type: 'object',
          properties: {
            필드: { type: 'string', enum: 수정필드s, description: '어휘의 "수정:" 줄에 적힌 이름 그대로.' },
            값: { type: 'string', description: '그 칸에 넣을 새 값. 사용자가 말한 것만 그대로.' }
          },
          required: ['필드', '값']
        }
      }
  }

  return { type: 'object', properties, required: ['source', '검색어', 'intent'] }
}

const 계획지침 = `너는 사용자의 말을 "조회 계획"으로 번역하는 역할만 한다. 답변 문장을 쓰지 마라.

규칙:
- source는 질문이 가리키는 소스의 key를 고른다. **이름은 소스를 말해주지 않는다** —
  각 소스의 "내용:" 한 줄을 보고 그 이름이 어디에 있을 법한지 판단하라("고양이" → 동물).
  소스를 직접 말하면("동물 몇 건이야") 그쪽이다.
- 검색어에는 찾을 이름의 일부만 넣는다. 조사·어미는 떼라("고양이에 대해" → "고양이").
  전체를 보는 질문이면 빈 문자열.
- 사용자가 말한 이름은 **그대로** 옮겨라. 어휘에서 못 본 이름이라고 비슷한 다른 이름으로
  바꾸지 마라("공룡" → "호랑이" 금지). 없는 이름이면 없는 대로 두면 된다 — 없다는 사실은
  앱이 조회해서 알아낸다. 이름을 바꾸는 순간 앱은 엉뚱한 행을 대상으로 잡는다.
  같은 이유로, 사용자가 이름을 말했으면 대상id를 채우지 마라(대상id는 대명사일 때만이다).
- 건수를 물으면 intent="count", 목록·명단을 물으면 intent="list",
  무언가를 시키면(실행·처리) intent="act",
  화면에 열어달라·골라달라·보여달라고 **한 건을 지목하면** intent="select".
  ("고양이 선택해줘", "그거 열어줘", "두 번째 거로 해줘" → select. 여러 건을 훑는 "목록 보여줘"는 list다.)`

const 행동지침 = `- 사용자가 무언가를 실행·처리해달라고 하면 행동에 해당 키를 넣는다.
- 행동은 **제안**일 뿐이다. 실행은 사용자가 답변 아래 버튼을 눌러서 한다. 네가 실행하는 게 아니다.
- 행동은 대상이 한 건으로 확정될 때만 걸린다. 대상의 이름을 **검색어**에 반드시 함께 넣어라.
  행동만 넣고 대상을 비우면 아무 일도 일어나지 않는다.
- 어휘의 행동 목록에 없는 일은 지목하지 마라.
- 사용자가 **남길 내용까지 말했으면**(따옴표로 묶은 말, "…라고 적어줘") 그 내용을 행동값에 그대로 넣어라.
  토씨 하나 바꾸지 말고, 검색어에는 절대 넣지 마라 — 검색어는 대상을 찾는 자리라
  그 내용으로 목록을 걸러 "그런 거 없다"가 된다.
  (「토마토에 기록추가해 "2222"」 → 검색어="토마토", 행동="do기록", 행동값="2222")
- 내용을 안 말했으면 행동값은 빈 문자열이다. 지어내지 마라 — 그때는 앱이 사용자에게 묻는다.
- 지우는 것도 행동이다. 목록에서 행을 없애달라고 하면("강아지 지워줘") 어휘에 \`do삭제\`가 있을 때만
  그 키를 지목하고, 대상 이름을 검색어에 넣어라. 없는 소스면 지울 수 없는 것이다 — 다른 행동으로 바꾸지 마라.`

const 필터지침 = `- 어휘에 "필터s:"가 있는 소스는 **축으로 거를 수 있다.** 사용자가 범주를 말하면
  검색어가 아니라 필터s에 "축=값"으로 넣어라("여름채소" → 필터s=["제철=여름"], 검색어="").
  범주를 검색어에 담으면 이름에 그 글자가 든 행만 걸려서 엉뚱한 결과가 된다.
- 축과 값은 어휘에 적힌 그대로만 쓴다. 옆의 괄호 숫자는 그 값에 걸리는 건수다 — 0건인 값은 고르지 마라.
- 이름과 범주를 같이 말했으면 둘 다 채운다("여름 채소 중에 감자" → 필터s=["제철=여름"], 검색어="감자").
- 이 조건은 **화면 목록에 그대로 걸린다.** 사용자가 눈으로 볼 목록을 좁히는 일이라고 생각하고 골라라.`

const 생성지침 = `- 목록에 **새 항목을 만들어달라**고 하면("동물 하나 추가해", "강아지 추가해줘") intent="create".
- 만들 이름을 말했으면 생성이름s에 그 이름들만 넣는다("강아지 추가해줘" → 생성이름s=["강아지"],
  "당근이랑 감자 추가해" → 생성이름s=["당근","감자"]).
  이름을 안 말했으면("동물 하나 추가해") 생성이름s는 **빈 배열**이다. 이름을 지어내지 마라 —
  이름 없이 빈 줄만 만들어도 된다. 사용자가 화면에서 채운다.
- 개수를 말했으면 생성개수에 그 수를 넣는다("채소 3개 추가해" → 생성개수=3, 생성이름s=[]).
  수를 안 말했으면 1이다. 이름을 말한 턴은 이름 수가 곧 개수라 생성개수를 신경 쓰지 않아도 된다.
- 이름 말고 **다른 칸까지 말했으면** 그것도 수정s에 쌍으로 넣어라
  ("기후대 열대인 강아지 추가해줘" → 생성이름s=["강아지"], 수정s=[{필드:"기후대",값:"열대"}]).
  만드는 턴에도 채울 칸을 나르는 자리는 수정s 하나다.
- 만드는 턴에는 검색어와 대상id를 비운다. 둘 다 **이미 있는 행**을 가리키는 자리라,
  만들 이름을 거기 담으면 "그런 건 없다"는 답이 나온다.
- 추가도 사용자가 답변 아래 버튼을 눌러야 일어난다. 네가 추가하는 게 아니다.
  버튼이 하는 일은 목록에 **빈 줄을 놓고 그 화면을 여는 것**까지다. 저장은 사용자가 화면에서 누른다.
- **"넣다/남기다/달다"가 늘 create는 아니다.** 어휘의 행동 목록에 있는 일을 시키는 말이면 act다
  ("고구마에 기록 하나 넣자" → intent="act", 행동="do기록", 검색어="고구마").
  create는 목록에 **행 자체**를 새로 만드는 것뿐이다("채소 하나 추가해").
  실측: 이 줄이 없을 때 lite 는 "기록 하나 넣자"를 create 로 읽고 '기록'이라는 이름의 채소를 만들려 했다.`

const 수정지침 = `- 이미 있는 행의 **값을 바꿔달라**고 하면("사과 원산지 제주로 바꿔줘", "고구마 좋아요 5로")
  행동="do수정", 수정s에 {필드, 값} 쌍을 넣는다.
- 한 문장이 여러 칸을 말하면 **쌍을 여러 개** 넣어라
  (「사과 이름 홍옥으로 원산지 제주로」 → 수정s=[{필드:"이름",값:"홍옥"},{필드:"원산지",값:"제주"}]).
- 대상의 이름은 **검색어**에 넣는다. 새 값은 검색어에 절대 넣지 마라 —
  검색어는 대상을 찾는 자리라, 새 값으로 목록을 걸러 "그런 거 없다"가 된다.
  (「사과 원산지 제주로 바꿔줘」 → 검색어="사과", 행동="do수정", 수정s=[{필드:"원산지",값:"제주"}])
- 어휘의 "수정:" 줄에 없는 칸은 지목하지 마라. 그 줄에 적힌 이름을 **그대로** 옮겨라.
- [숫자]가 붙은 칸에는 숫자만, [날짜]가 붙은 칸에는 날짜만 넣는다.
- 새 값을 안 말했으면 그 쌍은 넣지 마라. 값을 지어내지 마라 — 빈 칸은 앱이 폼에서 묻는다.
- 수정 턴이 아니면 수정s는 빈 배열이다.
- **값을 바꾸는 것과 행을 새로 만드는 것은 다르다.** 있는 행의 칸을 고치는 건 do수정이고,
  create는 목록에 행 자체를 새로 만드는 것뿐이다.`

const 지목지침 = `- 직전 턴에 제시된 항목을 가리키는 말("그거", "걔", "첫 번째 거", 이름을 그대로 말하는 경우)이면
  대상id에 그 항목의 키를 목록에 적힌 그대로 넣고 검색어는 비운다.`

const 화면지침 = `- [지금 화면]은 사용자가 열어놓고 보고 있는 대상이다.
  대상을 말하지 않고 행동만 말하면("do토스트 해줘", "실행해줘") 그 키를 대상id에 넣어라.
  문장에 이름이 없다고 대상이 없는 게 아니다.
- 대상을 고르는 순서: 1) 질문이 이름을 직접 말한다 → 그쪽. 2) 대명사("그거", "걔")면
  [직전 턴에 제시한 항목] — 방금 대화에서 세운 대상이 화면보다 우선한다. 3) 둘 다 없으면 [지금 화면].
- 이름도 대명사도 없으면 **반드시** [지금 화면]이다. [직전 턴에 제시한 항목]이 여러 건일 때
  그중 하나를 임의로 고르지 마라 — 그건 방금 훑어본 목록이지 사용자가 지목한 대상이 아니다.
- [지금 화면]에 "(방금 선택함)"이 붙어 있으면 사용자가 **직전 턴 이후에** 그것을 골랐다는 뜻이다.
  그때는 [직전 턴에 제시한 항목]을 무시하고 이 대상을 써라. 대화보다 이 행동이 나중이다.`

const 탭지침 = `- 어휘의 "묶음"은 그 행을 **열었을 때 보이는 화면의 묶음**이지 찾을 조건이 아니다.
  사용자가 한 건을 열면서 그 묶음을 말하면("영희 성격 보여줘") intent="select", 탭="성격"이고,
  그 이름을 검색어에 넣지 마라 — 그런 이름의 행은 없어서 0건이 된다.`

export interface PlannerResultV2 {
  /** 답변 호출에 실어 보낼 참조 블록(계획 실행 결과). */
  context: string
  plan: PlanV2 | null
  /** 이번 턴 프롬프트에 실제로 올라간 항목들. 다음 턴에 넘기면 후속 지목이 된다. */
  항목s: i항목V2[]
  /** 실제로 조회한 소스. 행동 화이트리스트(`행동키s`)를 읽는 데 쓴다. */
  source: i소스V2 | null
  /** 조건에 걸린 전체 건수. */
  총건수: number
}

const 빈결과: PlannerResultV2 = { context: '', plan: null, 항목s: [], source: null, 총건수: 0 }

/** 말 → (LLM) 계획 → 앱이 실행 → 결과 텍스트. 파이프라인 ① 번역 단계다(`./README.md`). */
export async function 계획조회V2(
  sources: i소스V2[],
  question: string,
  직전s: i항목V2[] = [],
  화면: i화면대상 | null = null,
  /**
   * 사용자가 **직전 턴 이후에** 화면 선택을 바꿨는가.
   *
   * 시간 순서는 앱만 안다 — 프롬프트 안에서 두 근거(직전 항목, 화면 선택)는 나란히 놓여
   * 어느 쪽이 나중인지 알 길이 없다. 지침으로 부탁해서 안 되는 건 **사실을 주면** 된다.
   */
  화면방금선택 = false,
  /**
   * 지금 화면(주소)에 걸려 있는 조회 조건. 앱만 아는 사실이라 앱이 넘긴다 —
   * `화면방금선택`과 같은 규율이다. 없으면 이어받지 않는다(첫 턴·다른 탭).
   */
  화면조건: i화면조건V2 | null = null
): Promise<PlannerResultV2> {
  if (!sources.length) return 빈결과

  await Promise.all(sources.map(s => s.load?.()))

  const 어휘 = sources.map(s => s.어휘()).join('\n\n')
  const 행동s = [...new Set(sources.flatMap(s => s.행동키s ?? []))]
  const can생성 = sources.some(s => !!s.초안)
  // 소스 간 합집합. 같은 키가 여러 소스에 있어도(`label`) 소스는 따로 정해지므로 섞이지 않고,
  // 한 소스에만 있는 키(`원산지`)는 그 자체가 소스를 말해준다.
  const 수정필드s = [...new Set(sources.flatMap(s => s.수정필드s.map(f => f.label)))]
  // 소스 간 합집합. 축 이름이 한 소스에만 있으면(`제철`) 그 자체가 소스를 말해준다.
  const 필터s = [...new Set(sources.flatMap(s => s.필터어휘s()))]
  const 정렬s = [...new Set(sources.flatMap(s => s.정렬어휘s()))]
  // 소스 간 합집합. 이름이 겹치는 소스가 생기면 어느 쪽 묶음인지는 **소스가 정해진 뒤** 앱이 가른다.
  const 탭s = [...new Set(sources.flatMap(s => s.탭어휘s()))]
  const 후보s = 지목후보s(직전s, 화면)

  // 후보 목록은 계획이 고를 enum과 **같은 키**로 적는다. 프롬프트와 스키마가 다른 표기를 쓰면
  // 모델이 둘을 섞어 쓰고, 그 순간 지목이 어디에도 안 맞는다.
  const 직전블록 = 직전s.length
    ? `\n\n[직전 턴에 제시한 항목]\n${직전s.map(x => `${x.source}:${x.id}\t${x.label}`).join('\n')}`
    : ''
  const 화면블록 = 화면?.id
    ? `\n\n[지금 화면] 사용자가 지금 보고 있는 대상${화면방금선택 ? ' (방금 선택함)' : ''}`
    + `\n${화면.source}:${화면.id}\t${화면.label}`
    : ''

  try {
    const res = await $fetch<{ json: PlanV2 | null }>('/api-etc/ai/chat', {
      method: 'POST',
      body: {
        system: [
          계획지침,
          직전s.length ? 지목지침 : '',
          화면 ? 화면지침 : '',
          행동s.length ? 행동지침 : '',
          can생성 ? 생성지침 : '',
          수정필드s.length ? 수정지침 : '',
          필터s.length ? 필터지침 : '',
          탭s.length ? 탭지침 : '',
          `\n[조회 가능한 소스와 어휘]\n${어휘}${직전블록}${화면블록}`
        ].filter(Boolean).join('\n'),
        level: 'lite',
        schema: 계획스키마V2(sources, 후보s, 행동s, can생성, 수정필드s, 필터s, 정렬s, 탭s),
        messages: [{ role: 'user', text: question }]
      }
    })

    const plan = res.json
    if (!plan) return { ...빈결과, context: 어휘 }

    /**
     * 대상을 지목했으면 **그 행이 실제로 있는 소스**를 따른다 — 계획이 소스를 빗나가면
     * 지목이 통째로 무시되고, 그 실패는 사용자에게 "그런 거 없다"로 보인다.
     *
     * **만드는 턴만 예외다.** `대상id`는 이미 있는 행을 가리키는 값이라 따라가면 소스가 바뀐다 —
     * 화면에 감자를 열어둔 채 "동물 하나 추가해"라고 하면 채소 표에 행이 생긴다.
     */
    const is생성 = plan.intent === 'create'
    /**
     * **이름을 말한 턴에는 지목을 버린다.**
     *
     * 지침에 적어놨지만 lite 는 안 지킨다 — 직전 턴에 사과 얘기를 하고 나면 "감자 제철 봄으로"에도
     * `대상id`에 사과를 채우고, 그러면 target이 과일이 되어 채소의 칸(`제철`)이 없으니 턴이 죽는다.
     * 검색어가 있다는 건 이 턴에 대상을 직접 말했다는 뜻이고, 그때 직전 지목은 잔상이다.
     */
    const 이름말함 = !!String(plan.검색어 ?? '').trim()
    const 지목 = !is생성 && !이름말함 && plan.대상id ? 후보s.find(x => x.키 === plan.대상id) : undefined
    const target = sources.find(s => s.key === (지목?.source || plan.source)) ?? sources[0]!

    // 소스가 정해진 뒤에는 접두어를 뗀다. 후보에 없는 지목은 비워 검색으로 흘려보낸다.
    // 만드는 턴은 조회 조건을 통째로 비운다 — 아직 없는 이름이라 참조가 "총 0건"으로 물들면 안 된다.
    // 잔상으로 판정된 지목은 실행 계획에서도 지운다(`계획실행V2`은 대상id를 먼저 본다).
    const 실행plan: PlanV2 = is생성
      ? { ...plan, 검색어: '', 대상id: undefined }
      : 이름말함
        ? { ...plan, 대상id: undefined }
        : plan.대상id
          ? { ...plan, 대상id: 지목?.id }
          : plan

    // 이번 턴이 말하지 않은 축은 화면에 걸린 것을 그대로 이어받는다(축 단위 덮어쓰기).
    // 조회 조건이 확정되는 마지막 자리다 — 아래 `조회`(건수)와 `조회쿼리`(주소)가 같은 값을 본다.
    const 최종plan = 필터이어받기(실행plan, target, 화면조건)

    // 시키는 턴은 좁게, 목록은 넓게, 건수는 표본만. 만드는 턴은 아예 안 싣는다(볼 행이 없다).
    // select 가 넓은 이유: 한 건으로 안 좁혀졌을 때 앱이 그리는 명단이 곧 고르는 자리라
    // (줄을 누르면 선택된다) 후보가 잘려 있으면 고를 방법 자체가 사라진다.
    const max = is생성 ? 0 : plan.intent === 'act' ? 5 : plan.intent === 'count' ? 5 : 30

    const { text, 항목s, 총건수 } = target.조회(최종plan, max)
    return { context: text, plan: 최종plan, 항목s, source: target, 총건수 }
  } catch {
    // 계획 수립이 실패하면 어휘만이라도 넘겨 "확인 필요"를 유도한다(전량 덤프로 되돌아가지 않는다).
    return { ...빈결과, context: 어휘 }
  }
}

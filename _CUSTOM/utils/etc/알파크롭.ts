/**
 * 알파가 박힌 그림(누끼 뜬 인물)을 **규격 프레임에 앉힌다**.
 *
 * 증명사진은 장마다 얼굴 크기가 같아야 하는데, 그림 모델은 `얼굴이 높이의 75%` 같은 지시를
 * 재서 지키지 못한다. 몇 %인지는 자로 재는 일이라 프롬프트가 아니라 여기서 한다 —
 * 지시문은 코드가 못 하는 것(피부·표정·바탕색)에만 쓰는 게 맞다.
 *
 * **이 파일은 증명사진을 모른다.** 정수리를 어디에 앉힐지·머리를 얼마나 크게 할지는
 * 부르는 쪽이 `i규격`으로 준다 (`model캐릭터`의 `증명사진규격`).
 *
 * ## 무엇을 자로 삼는가
 *
 * 규격이 말하는 자는 **정수리~턱**인데 알파 실루엣은 이목구비를 모른다. 그래서 예전에는 실루엣의
 * **머리 폭**을 재서 `폭 = 길이 × 0.65` 라는 사람 평균으로 환산했다. 이 환산 자체는 어쩔 수 없지만,
 * **무엇의 폭을 쟀는지가 문제였다** — 실루엣이 재는 것은 두개골이 아니라 **머리카락까지 친 폭**이라,
 * 숱이 많으면 부풀어 얼굴이 그만큼 작게 앉고 짧은 머리는 반대로 크게 앉는다. `머리폭` 상수를 아무리
 * 잘 골라도(0.68) 그 값은 양끝의 오차를 반씩 나눠 가질 뿐 없앨 수가 없다. 장마다 얼굴 크기가
 * 달라 보이던 것이 이것이다.
 *
 * 그래서 폭을 **얼굴에서 잰다**(`얼굴재기`). 키잉이 끝난 그림에는 알파만이 아니라 RGB 가 살아
 * 있으므로, 살색으로 얼굴을 골라내면 머리카락을 빼고 귀~귀 폭을 잴 수 있다. 환산 한 번은 그대로
 * 남지만(사람마다 다른 얼굴 비율, ±4% 남짓) **머리 모양이라는 훨씬 큰 항이 사라진다.**
 *
 * ### 턱은 왜 안 찾는가
 *
 * 규격이 말하는 자를 직접 재는 게 최선이라 턱을 찾아 봤는데, 정면 사진에서는 **턱이 극값이 아니다**.
 * 살색 폭은 광대에서 가장 넓고 턱선을 따라 좁아지다가 목에서 **평평해진다** — 턱 끝 아래로도
 * 목이 계속 같은 폭으로 보이기 때문이다. 골짜기가 아니라 고원이라 "가장 좁은 줄"은 턱이 아니라
 * 목 아래 끝(옷깃)을 가리킨다. 고원이 시작되는 무릎을 잡으면 턱보다 조금 위에 걸리는데, 그 차이가
 * 목 굵기에 따라 흔들려서 결국 대리 변수 하나를 다른 대리 변수로 바꾸는 꼴이 된다.
 * (합성 표본으로 확인했다. 턱 대신 옷깃 y 를 집었다)
 *
 * 턱을 제대로 집으려면 이목구비 landmark 모델이 필요하다. 여기서 공짜로 얻을 수 있는 것 중에는
 * **극값(광대 폭)이 가장 덜 흔들린다** — 최댓값이라 한 줄의 잡티나 문턱 흔들림에 밀리지 않는다.
 *
 * ### 어깨는 왜 안 되는가
 *
 * 증명사진은 가슴에서 자르는 구도라 어깨가 프레임 좌우 끝까지 차 있어(`누끼.ts` 의 `키색추정` 이
 * 아래 두 귀를 배경이 아니라 옷으로 관찰한 바로 그 이유) 폭이 애초에 재지지 않는다. 재진다 해도
 * 어깨너비는 체격·옷·자세로 머리보다 더 흔들리고, 규격에 어깨 조항은 없다.
 */

export interface i규격 {
  /** 프레임 가로:세로 비 (3:4 면 `가로: 3, 세로: 4`) */
  가로: number
  세로: number
  /** 정수리가 앉는 높이. 프레임 높이 기준 0~1 (위 모서리가 0) */
  정수리: number
  /**
   * 얼굴(귀~귀)이 차지하는 폭. 프레임 가로 기준 0~1.
   * 주면 살색으로 얼굴을 찾아 이 폭으로 앉히고, 못 찾으면 `머리폭` 으로 물러난다.
   */
  얼굴폭?: number
  /** 머리(머리카락까지)가 차지하는 폭. 프레임 가로 기준 0~1. 얼굴을 못 찾았을 때의 대비책 */
  머리폭: number
  /** 이 알파(0~1) 이상이면 인물로 친다 */
  문턱?: number
}

export interface i머리자리 {
  /** 정수리 y (px) */
  정수리: number
  /** 머리 좌우 한가운데 x (px) */
  중심x: number
  /** 관자놀이 폭 (px) */
  폭: number
}

export interface i얼굴자리 {
  /** 얼굴에서 가장 넓은 줄의 폭 (px). 귀~귀 — 머리카락은 안 든다 */
  광대폭: number
  /** 그 줄의 y (px) */
  광대y: number
  /** 얼굴 한가운데 x (px). 실루엣 중심과 달리 가르마·한쪽으로 넘긴 머리에 안 밀린다 */
  중심x: number
}

/**
 * 알파 실루엣에서 **정수리와 머리 폭**을 잰다.
 *
 * 여기서 나오는 폭은 **머리카락까지 친 폭**이다. 배율로 쓰기엔 숱을 타므로(파일 첫 주석) 보통은
 * `얼굴재기` 의 탐색 범위를 잡는 데만 쓰이고, 살색으로 얼굴을 못 찾았을 때만 배율로 쓰인다.
 *
 * 폭은 **관자놀이**에서 잰다. 위에서 내려오면 실루엣은 정수리에서 관자놀이까지 넓어지다가
 * 턱·목에서 좁아지고 어깨에서 다시 확 넓어지는데, 어깨까지 먹으면 머리가 실제보다 크게 잡혀
 * 얼굴이 도리어 작게 앉는다. 그래서 **처음으로 좁아지기 시작하는 지점에서 멈춘다**.
 * 긴 머리처럼 좁아지는 구간이 없는 실루엣을 위해 탐색 자체도 위 40%로 잘라 둔다.
 *
 * 키잉이 남긴 점 하나를 정수리로 오인하지 않도록, 가로 1% 도 안 되는 줄은 인물로 세지 않는다.
 */
export function 머리재기(픽셀: ImageData, 문턱 = 0.5): i머리자리 | null {
  const { data, width: w, height: h } = 픽셀
  const 알파문턱 = Math.round(Math.min(Math.max(문턱, 0), 1) * 255)
  const 최소폭 = Math.max(2, Math.round(w * 0.01))

  let 정수리 = -1
  let 폭 = 0
  let 왼 = 0
  let 오 = 0
  let 좁아진줄 = 0

  for (let y = 0; y < h; y++) {
    let l = -1
    let r = -1
    for (let x = 0; x < w; x++) {
      if (data[(y * w + x) * 4 + 3]! >= 알파문턱) {
        if (l < 0) l = x
        r = x
      }
    }
    if (l < 0 || r - l + 1 < 최소폭) continue

    if (정수리 < 0) 정수리 = y
    else if (y - 정수리 > h * 0.4) break

    const 이줄 = r - l + 1
    if (이줄 >= 폭) {
      폭 = 이줄
      왼 = l
      오 = r
      좁아진줄 = 0
    } else if (이줄 < 폭 * 0.92) {
      // 한 줄만 보고 멈추면 머리카락 삐침 하나에 속는다. 연달아 좁아져야 턱으로 친다.
      if (++좁아진줄 >= 3) break
    } else {
      좁아진줄 = 0
    }
  }

  if (정수리 < 0 || 폭 <= 0) return null
  return { 정수리, 중심x: (왼 + 오 + 1) / 2, 폭 }
}


/**
 * 살색의 **기준값을 그림에서 읽는다**. 상수로 박지 않는 이유는 `누끼.ts` 의 `키색추정` 과 같다 —
 * 피부톤·조명·키잉이 걷어낸 초록기의 잔량이 장마다 달라서, 절대 문턱은 어떤 장에서는 뺨을 놓치고
 * 어떤 장에서는 머리카락을 먹는다.
 *
 * 얼굴 한가운데 세로 띠(이마 아래~코)만 뜬다. 좌우로 넓히면 머리카락이 들어오고, 위아래로
 * 넓히면 정수리와 목이 들어온다. 그 띠 안에서도 앞머리가 이마를 덮을 수 있으므로 평균이 아니라
 * **밝기 순 60% 지점의 픽셀**을 쓴다 — 머리카락은 살보다 어두우므로 아래로 가라앉고, 눈썹·눈동자
 * 같은 작은 어두운 덩어리도 같이 가라앉는다.
 */
function 살색기준(
  픽셀: ImageData,
  머리: i머리자리,
  알파문턱: number
): { 합: number, r비: number, g비: number } | null {
  const { data, width: w, height: h } = 픽셀
  const x0 = Math.max(0, Math.round(머리.중심x - 머리.폭 * 0.22))
  const x1 = Math.min(w, Math.round(머리.중심x + 머리.폭 * 0.22))
  const y0 = Math.max(0, Math.round(머리.정수리 + 머리.폭 * 0.3))
  const y1 = Math.min(h, Math.round(머리.정수리 + 머리.폭 * 0.9))

  const 표본: number[] = []
  for (let y = y0; y < y1; y += 2) {
    for (let x = x0; x < x1; x += 2) {
      const i = (y * w + x) * 4
      if (data[i + 3]! < 알파문턱) continue
      표본.push(i)
    }
  }
  if (표본.length < 32) return null

  표본.sort((a, b) => (data[a]! + data[a + 1]! + data[a + 2]!) - (data[b]! + data[b + 1]! + data[b + 2]!))
  const i = 표본[Math.floor(표본.length * 0.6)]!
  const r = data[i]!, g = data[i + 1]!, b = data[i + 2]!
  const 합 = r + g + b
  if (합 <= 0) return null
  return { 합, r비: r / 합, g비: g / 합 }
}

/**
 * 살색에서 **얼굴의 가장 넓은 줄(귀~귀)을 잰다**. 못 찾으면 null — 부르는 쪽은 머리 폭으로 물러난다.
 *
 * 살색 판정은 두 가지를 본다. **밝기**는 기준 살색 대비 0.55~1.5 배 — 머리카락·눈썹·턱밑 그늘이
 * 여기서 떨어진다. **색상**은 밝기를 나눈 `r/합, g/합` 이 기준에서 0.05 안 — 흰 셔츠·회색 옷처럼
 * 무채색인 것과 입술처럼 붉은 쪽으로 치우친 것이 여기서 떨어진다. 두 축을 나눠 보는 이유는
 * `누끼.ts` 의 `초록기` 와 같다: 밝기 하나로 재면 밝은 옷과 밝은 살을 못 가른다.
 *
 * 폭은 그 줄의 **왼쪽 끝~오른쪽 끝**이다. 살색 픽셀 수가 아니다 — 눈·눈썹·안경테가 줄 가운데를
 * 뚫어도 귀~귀 거리는 그대로이기 때문이다. 대신 뻗은 길이의 절반도 못 채우는 줄은 버린다.
 * 뺨 하나와 저 멀리 떨어진 살색 점 하나를 이어 폭으로 세지 않기 위해서다.
 *
 * 귀가 폭에 들어간다. 지시문이 `Both ears visible` 을 보장하므로 장마다 들쭉날쭉하지 않고,
 * 규격 상수는 그 전제 위에서 잡혀 있다 (`model캐릭터` 의 `증명사진규격`).
 */
export function 얼굴재기(픽셀: ImageData, 머리: i머리자리, 문턱 = 0.5): i얼굴자리 | null {
  const { data, width: w, height: h } = 픽셀
  const 알파문턱 = Math.round(Math.min(Math.max(문턱, 0), 1) * 255)

  const 기준 = 살색기준(픽셀, 머리, 알파문턱)
  if (!기준) return null

  const 색상문턱 = 0.05 * 0.05
  const is살색 = (i: number) => {
    if (data[i + 3]! < 알파문턱) return false
    const r = data[i]!, g = data[i + 1]!, b = data[i + 2]!
    const 합 = r + g + b
    if (합 <= 0) return false
    const 밝기비 = 합 / 기준.합
    if (밝기비 < 0.55 || 밝기비 > 1.5) return false
    const dr = r / 합 - 기준.r비
    const dg = g / 합 - 기준.g비
    return dr * dr + dg * dg <= 색상문턱
  }

  // 탐색 상자. 아래로 열어 두면 앞섶으로 드러난 목·가슴이 광대보다 넓게 잡힐 수 있으므로
  // 얼굴이 들어갈 만큼만 본다. 광대는 정수리에서 머리 폭의 0.25~1.15 배 아래에 있다.
  const x0 = Math.max(0, Math.round(머리.중심x - 머리.폭 * 0.8))
  const x1 = Math.min(w, Math.round(머리.중심x + 머리.폭 * 0.8))
  const y0 = Math.max(0, Math.round(머리.정수리 + 머리.폭 * 0.25))
  const y1 = Math.min(h, Math.round(머리.정수리 + 머리.폭 * 1.15))
  if (x1 - x0 < 4 || y1 - y0 < 4) return null

  let 광대폭 = 0
  let 광대y = -1
  let 광대왼 = 0
  let 광대오 = 0

  for (let y = y0; y < y1; y++) {
    let l = -1
    let r = -1
    let 수 = 0
    for (let x = x0; x < x1; x++) {
      if (!is살색((y * w + x) * 4)) continue
      if (l < 0) l = x
      r = x
      수++
    }
    if (l < 0) continue
    const 뻗음 = r - l + 1
    if (수 < 뻗음 * 0.45) continue
    if (뻗음 > 광대폭) {
      광대폭 = 뻗음
      광대y = y
      광대왼 = l
      광대오 = r
    }
  }

  // 얼굴이라 부를 만한 덩어리가 없다 (살색 기준 자체가 빗나갔을 때)
  if (광대y < 0 || 광대폭 < 머리.폭 * 0.35) return null
  // 광대는 얼굴 길이의 절반 남짓 위치이므로 정수리에서 제 폭의 1.4 배보다 더 내려가지 않는다.
  // 넘었다면 얼굴이 아니라 아래쪽(목·가슴)을 집은 것이다.
  if (광대y - 머리.정수리 > 광대폭 * 1.4) return null

  return { 광대폭, 광대y, 중심x: (광대왼 + 광대오 + 1) / 2 }
}

/**
 * 잰 자리를 규격에 맞춰 **옮겨 담는다**. 실패하면 null — 부르는 쪽은 원본을 그대로 쓰면 된다.
 *
 * 확대·축소를 하지 않는다. 출력 캔버스를 `잰폭 / 규격폭` 으로 **잡아서** 비율을 맞추므로 그림은
 * 평행이동만 하면 된다 — 리샘플링이 없으니 방금 살려낸 모공이 다시 뭉개지지 않는다.
 * (프레임의 픽셀 크기는 장마다 다르지만 비율과 얼굴 위치는 같다. 화면은 어차피 맞춰 늘린다)
 *
 * 세로 위치는 정수리를 그대로 쓴다. 규격의 여백 조항이 머리카락까지 친 정수리를 말하기 때문이다
 * (한국 여권사진 기준의 `정수리`는 헤어스타일을 포함한다). 배율만 얼굴에서 가져온다.
 *
 * 좌우는 얼굴 한가운데에 맞춘다. 실루엣 중심을 쓰면 가르마나 한쪽으로 넘긴 머리가 얼굴을 옆으로
 * 밀어낸다 — 얼굴을 못 찾은 장에서만 예전처럼 실루엣 중심으로 물러난다.
 *
 * 프레임이 원본 밖으로 나가는 부분은 투명으로 남는다. 배경이 이미 지워진 뒤라 공짜다 —
 * **다만 원본에서 잘려나간 머리는 되돌리지 못하니**, 지시문은 넉넉하게 찍으라고 해야 한다.
 */
export async function do알파규격크롭(blob: Blob, 규격: i규격): Promise<Blob | null> {
  if (!(규격.머리폭 > 0) || !(규격.가로 > 0) || !(규격.세로 > 0)) return null
  try {
    const 판 = await 블롭펼치기(blob)
    if (!판) return null

    const 머리 = 머리재기(판.픽셀, 규격.문턱)
    if (!머리) {
      console.warn('[규격크롭] 실루엣을 찾지 못했습니다 — 누끼만 살립니다')
      return null
    }

    const 얼굴 = 규격.얼굴폭 && 규격.얼굴폭 > 0 ? 얼굴재기(판.픽셀, 머리, 규격.문턱) : null
    if (규격.얼굴폭 && !얼굴) {
      console.warn('[규격크롭] 살색으로 얼굴을 찾지 못했습니다 — 머리 폭으로 앉힙니다')
    }

    const 잰폭 = 얼굴 ? 얼굴.광대폭 : 머리.폭
    const 규격폭 = 얼굴 ? 규격.얼굴폭! : 규격.머리폭
    const 중심x = 얼굴 ? 얼굴.중심x : 머리.중심x

    const 출력 = document.createElement('canvas')
    출력.width = Math.max(1, Math.round(잰폭 / 규격폭))
    출력.height = Math.max(1, Math.round(출력.width * (규격.세로 / 규격.가로)))

    const ctx = 출력.getContext('2d')
    if (!ctx) return null

    ctx.drawImage(
      판.canvas,
      Math.round(출력.width / 2 - 중심x),
      Math.round(출력.height * 규격.정수리 - 머리.정수리)
    )
    return await 캔버스블롭(출력)
  } catch (e) {
    console.error('[규격크롭] 실패 — 누끼만 살립니다', e)
    return null
  }
}

/** 트리거가 만든 그대로인 회차인가 — 아무도 안 건드린 1회차만 씨앗이 채운다. 사람이 고친 행은 놔둔다. */
const is빈회차 = (신청받기: model신청받기) => 신청받기.공개 === 'PREPARING' && 신청받기.문항s.length === 0 && 신청받기.정원 === 0

/**
 * 콘텐츠마다 1회차를 **채운다.** 트리거가 만든 빈 1회차는 UPDATE, 회차가 아예 없는 콘텐츠
 * (트리거를 걸기 전 데이터)는 하나 만든다. 이미 채워졌거나 사람이 손댄 회차는 건너뛴다 —
 * 두 번 눌러도 안 늘고 안 덮인다.
 */
export const do신청받기씨앗 = async () => {
  const 신청받기repo = model신청받기s.getInstance()
  const repos = 콘텐츠repos()
  // 콘텐츠 목록까지 **여기서** 읽는다. 단독으로 부를 때(초기값설정 버튼) 목록이 비어 있어 조용히 0건이 되면 안 된다.
  // 회차는 강제로 — 방금 트리거가 만든 행을 표버전 게이트 안에서 놓칠 수 있다.
  await Promise.all([
    신청받기repo.reads(false, true),
    ...Object.values(repos).map(repo => repo.reads())
  ])

  const 대상s: i씨앗대상[] = (Object.entries(repos) as [i신청받기대상, { list: any }][]).flatMap(([표, repo]) =>
    (toValue(repo.list) as i씨앗대상['콘텐츠'][])
      .filter(콘텐츠 => 콘텐츠.stateId != null)
      .map(콘텐츠 => ({ 표, 콘텐츠, 씨앗: 씨앗By제목[콘텐츠.제목] ?? 기본씨앗 }))
  )

  const 오늘 = mDayjs().startOf('day')
  const 채울s: model신청받기[] = []
  const 만들s: Parameters<typeof 신청받기repo.create0>[0][] = []

  for (const x of 대상s) {
    const 씨앗 = x.씨앗
    const 신청시작 = 오늘.add(씨앗.신청시작일차 ?? 0, 'day')
    const 신청끝 = 신청시작.add(씨앗.신청일수 ?? 30, 'day')
    const 요금 = 씨앗.요금 ?? 0
    const 값 = {
      applicationStartDate: 신청시작.toDate(),
      applicationEndDate: 신청끝.toDate(),
      usageStartDate: 신청시작.toDate(),
      usageEndDate: 신청시작.add(씨앗.사용일수 ?? 60, 'day').toDate(),
      priceType: (요금 > 0 ? 'PAID' : 'FREE') as i신청받기요금구분,
      price: 요금,
      maxParticipants: 씨앗.정원 ?? 0,
      status: 씨앗.공개 ?? 'PUBLISHED',
      allowGuest: 씨앗.비회원허용 ?? false,
      questions: 씨앗.문항s.map(문항행)
    }

    const 회차s = 신청받기repo.getsBy대상(x.표, x.콘텐츠.stateId)
    if (!회차s.length) {
      만들s.push({ ...신청받기repo._init(), ...값, round: 1, [i신청받기대상FK열[x.표]]: String(x.콘텐츠.stateId) })
      continue
    }
    const 첫회차 = 회차s[0]!
    if (!is빈회차(첫회차)) continue
    Object.assign(첫회차.state, 값)
    채울s.push(첫회차)
  }

  if (!채울s.length && !만들s.length) {
    useAlert().log('신청받기 씨앗', '채울 회차가 없습니다 — 이미 채워졌거나 콘텐츠가 없습니다.')
    return []
  }

  const 만든s = 만들s.length ? await 신청받기repo.creates(만들s) : []
  if (채울s.length) await 신청받기repo.do모두저장(채울s)

  const 문항수 = [...채울s, ...만든s].reduce((sum, 신청받기) => sum + 신청받기.문항s.length, 0)
  useAlert().log('신청받기 씨앗', `회차 ${채울s.length + 만든s.length}건에 문항 ${문항수}개를 채웠습니다.`)
  return [...채울s, ...만든s]
}

/**
 * 콘텐츠 5종을 seed로 올리고, 이어서 트리거가 만든 1회차를 씨앗대로 채운다. 화면에서 버튼 하나로 부르는 자리.
 * 각 단계는 목록이 비어 있을 때만 도므로(`do초기데이터`), 여러 번 눌러도 안전하다.
 */
export const do신청세트초기데이터 = async (opts?: { skipConfirm?: boolean }) => {
  const skipConfirm = opts?.skipConfirm ?? true
  const repos = 콘텐츠repos()
  for (const repo of Object.values(repos))
    await (repo as any).do초기데이터({ skipConfirm, ensureRead: true })
  const 회차s = await do신청받기씨앗()
  await do신청기록씨앗()
  return 회차s
}

// ── 신청 기록 ──────────────────────────────────────────────────────────────────

/** FNV-1a — 제목에서 인원·신청자·답을 뽑는다. 랜덤이면 돌릴 때마다 「신청 12/30」 이 바뀌어 화면 대조가 안 된다. */
const 해시 = (s: string): number => {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/** 신청할 사람 — 모임 회원(학습자)과 지원받은 협회 사람(준회원). 운영진·담당자는 신청하지 않는다. */
const 신청자codes = i회원seed
  .filter(m => m.code && !m.isSleeping && !m.역할codes?.some(r => r === 'admin' || r === 'manager')
    && m.역할codes?.some(r => r === 'learner' || r === 'associate'))
  .map(m => m.code!)

/** 문답물 답 — 선택형만 채운다(집계 화면이 선택지 막대를 그린다). 서술형은 비워 둔다. */
const 답s만들기 = (문항s: readonly i문항[], 씨앗: number): i신청dto['answers'] => {
  const 답s: i신청dto['answers'] = {}
  문항s.forEach((q, i) => {
    const k = 해시(`${씨앗}#${i}`)
    const 선택지s = q.type === 'OX' ? ['O', 'X'] : q.options.map(o => o.value || o.label)
    if (!선택지s.length) return
    // 채점 문항은 열에 일곱쯤 맞힌다.
    if (q.answerKey?.length && k % 10 < 7) {
      답s[q.id] = [...q.answerKey]
      return
    }
    if (q.type === 'MULTI') {
      답s[q.id] = 선택지s.filter((_, j) => ((k >>> j) & 3) === 0).slice(0, 3)
      if (!답s[q.id]!.length) 답s[q.id] = [선택지s[k % 선택지s.length]!]
      return
    }
    if (q.type === 'SINGLE' || q.type === 'SCALE' || q.type === 'OX') {
      // 앞쪽 선택지에 몰리게(척도라면 「그렇다」 쪽) — 실제 응답 분포처럼.
      const j = Math.min(선택지s.length - 1, Math.floor(((k % 100) / 100) ** 1.8 * 선택지s.length))
      답s[q.id] = [선택지s[j]!]
    }
  })
  return 답s
}

/**
 * 회차마다 **신청 기록**을 깐다 — 목록의 「신청 12 / 30명」·설문 「응답 41」이 0 으로만 보이면 운영 중인 사이트가 아니다.
 *
 * - 신청이 **이미 시작된 공개 회차**만. 정원이 있으면 정원의 30~95%(마감된 건은 가득), 없으면 5~18명.
 * - 신청자는 `i회원seed` 의 학습자·준회원(`code` → `시드PK`). 등록부가 비었으면(회원을 따로 넣은 뒤 단독 실행) 조용히 건너뛴다.
 * - 문답물(설문·퀴즈·투표)은 선택형 답을 채운 **제출**, 수업·행사는 대부분 **승인** · 몇은 대기·취소.
 * - 신청 표가 **비었을 때만** 돈다 — 사람이 낸 신청 위에 덧쌓지 않는다.
 */
export const do신청기록씨앗 = async () => {
  const 신청repo = model신청s.getInstance()
  const 신청받기repo = model신청받기s.getInstance()
  await Promise.all([신청repo.reads(false, true), 신청받기repo.reads(false, true)])
  if (toValue(신청repo.list).length) return []

  const 회원ids = 신청자codes.map(code => 시드PK.찾기('members', code)).filter((id): id is string => Boolean(id))
  if (!회원ids.length) return []

  const 오늘 = mDayjs().startOf('day')
  const 만들s: Parameters<typeof 신청repo.create0>[0][] = []

  for (const 회차 of toValue(신청받기repo.list) as model신청받기[]) {
    const st = 회차.state
    if (회차.공개 !== 'PUBLISHED' || !st?.applicationStartDate) continue
    const 시작 = mDayjs(st.applicationStartDate)
    if (시작.isAfter(오늘)) continue

    const 씨앗 = 해시(`${회차.label}#${회차.stateId}`)
    const is마감 = mDayjs(st.applicationEndDate).isBefore(오늘)
    const 정원 = 회차.정원
    const 인원 = Math.min(
      회원ids.length,
      정원 > 0 ? Math.max(1, Math.round(정원 * (is마감 ? 1 : 0.3 + ((씨앗 % 66) / 100)))) : 5 + (씨앗 % 14)
    )
    const 경과일 = Math.max(1, 오늘.diff(시작, 'day'))

    for (let n = 0; n < 인원; n++) {
      const k = 해시(`${씨앗}#${n}`)
      const memberId = 회원ids[(씨앗 + n * 7) % 회원ids.length]!
      const 신청일 = 시작.add(k % 경과일, 'day').hour(9 + (k % 12)).minute(k % 60)
      const 상태: i신청dto['status'] = 회차.is문답물
        ? 'SUBMITTED'
        : (k % 13 === 0 ? 'CANCELED' : k % 5 === 0 && !is마감 ? 'PENDING' : 'APPROVED')
      만들s.push({
        ...신청repo._init(),
        enrollableId: String(회차.stateId),
        memberId,
        status: 상태,
        answers: 회차.is문답물 ? 답s만들기(회차.문항s, k) : {},
        submittedAt: 회차.is문답물 ? 신청일.add(k % 3, 'hour').toISOString() : null,
        createdAt: 신청일.toISOString()
      } as Parameters<typeof 신청repo.create0>[0])
    }
  }

  if (!만들s.length) return []
  const 만든s = await 신청repo.creates(만들s)
  // 서버(`db_low.withCreateMeta`)가 `createdAt` 을 지금으로 덮는다 — 신청일이 전부 오늘이 되지 않게 되돌린다(게시글 시드와 같은 뒤처리).
  // `creates` 는 넘긴 순서대로 돌려준다.
  // 비교 없이 되돌린다 — 모델 state 는 보낸 값을 들고 있어 「같으면 건너뛴다」가 늘 참이 된다(`model회원게시글.do초기데이터` 주석).
  const 고칠s = 만든s.filter((row, i) => {
    const 원래 = (만들s[i] as { createdAt?: string }).createdAt
    if (!원래) return false
    row.state.createdAt = 원래
    return true
  })
  if (고칠s.length) {
    await 신청repo.updates(고칠s.map(row => row.state))
    await 신청repo.reads(false, true)
  }
  useAlert().log('신청 기록 씨앗', `신청 ${만든s.length}건을 넣었습니다.`)
  return 만든s
}


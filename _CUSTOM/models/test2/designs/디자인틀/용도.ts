/**
 * 디자인틀 용도 정의 — "이 디자인틀이 무엇을 채울 수 있는가"의 유일한 출처.
 *
 * 한때 이 파일 이름이 `_catalog.ts` 였다. 그때 '카탈로그'가 셋을 동시에 가리켰다 —
 * 이 파일(용도 어휘) · 왼쪽 패널(`목록.vue`) · 저장 표(`form-catalogs`). 내용물이 셋 다
 * 달라서 각자 이름으로 갈랐다: **용도 · 디자인틀목록 · `design-templates`**. 지금 이 파일에 배치는 없다.
 *
 * 두 층이 있는데 **소유자가 다르다.**
 *   · **디자인틀** — 사용자가 고르고 고치는 한 벌. 규격 + 면(배경 · 표식 · 글자) 배치가 이미 합쳐져
 *     있다 (`명함_1` 은 앞뒤 2면, `명함_2` 는 1면). **데이터다.** 이 파일에 배치가 하나도
 *     없는 이유이고, `model디자인틀` 의 표가 통째로 그것이다. 표에 대고 묻는 일(`용도별디자인틀s` ·
 *     `열기`)도 이 파일이 아니라 그 모델의 몫이다 — 여기는 표를 모른다.
 *   · `용도정의s` — 그 디자인틀이 채울 수 있는 값의 목록. 배치만 다른 디자인틀 여럿이 하나를 공유한다.
 *     **코드다.** 자리 이름은 나중에 실데이터를 이을 때 코드가 맞대어 볼 어휘라서다.
 *
 * 한때 이 파일이 시작 배치 넷(`등급증_1` · `포스터_1` · `명함_1` · `명함_2`)을 상수로 들었다.
 * 그때 이 편집기는 만든 것이 남지 않는 도구였다 — 디자인틀이 태어나는 곳이 이 배열뿐이라 사람이
 * 캔버스에서 한 일은 갈 곳이 없었고, 디자인틀을 갈아탈 때 뜨는 `"지금 배치한 글자와 표식이 사라집니다"`
 * 확인창이 그걸 막는 유일한 장치였다. 그 넷은 지금 `_CUSTOM/localDB/design-templates.json` 의
 * 다른 행들과 나란히 있고, 코드가 들어야 할 만큼 굳어지면 그때 `_CUSTOM/models/test2/seeds/`
 * 로 내려가면 된다. 코드에 두는 것과 데이터로 두는 것 사이에 상수 배열이 낄 자리는 없다.
 *
 * 그래서 **디자인틀이 하나도 없을 수 있다.** `model디자인틀s.디자인틀찾기` 가 `null` 을 돌려주고 캔버스가
 * 빈 디자인틀(`빈디자인틀`)으로 서는 것이 그 결과다 — 폴백으로 세울 붙박이가 이제 없다.
 *
 * **실값 층은 여기 없다 — 그러나 이제 어딘가에는 있다.** 값을 대는 곳은 `model회원.디자인틀주입`
 * 이고, 이 파일은 여전히 그쪽을 모른다. 어휘가 값을 들면 용도 하나가 회원에 묶여 버려서,
 * 같은 등급증을 다른 대상(강사·기관)에게 발급할 길이 막힌다.
 *
 * 한때 이 파일이 실값을 만들려 한 적이 있다(가짜 소스 `_source.ts` 와 `값s()`). 지운 이유를
 * 적어 둔다: 소스를 비운 채 조립 함수를 돌리자 종이에 `위 사람은 undefined 과정(undefined,
 * undefined)을` 이 찍혔다. 없는 값을 만들어 넣으면 없다는 사실이 사라지고 그럴듯한 쓰레기가
 * 앉는다. 그래서 지금 렌더러도 값이 없는 자리를 **비운 채로** 내보낸다(`렌더.ts` 의 `i주입`).
 *
 * 그래서 이 파일에 남은 축은 둘뿐이고, 둘 다 디자인틀을 짜는 데만 쓰인다.
 *
 *   1. 자리 — 글자 상자에 붙은 **꼬리표** 하나. **사용자가 소유**한다.
 *             목록을 따로 들지 않는다 — 상자를 고치는 순간 어긋나므로 `꼬리표s()`로 도출한다.
 *   2. 어휘 — 그 용도가 아는 자리 이름의 목록 (`용도정의s[].변수s`). **코드가 소유**한다.
 *             값을 대는 게 아니라 이름과 예시(`i변수.샘플`)만 댄다. `자리현황()` 이 둘을 맞대어
 *             용도가 모르는 이름이 붙은 상자(대개 오타)를 잡는다.
 *
 * 그래서 자리 상자는 `내용`(주입받을 칸)을 **비운 채로** 깔리고, 그 자리에 무엇이 들어올지는
 * 옆의 `예시` 가 실제 길이로 보여 준다. 화면에 뜨는 건 `내용 || 예시` — 주입이 붙기 전에는 예시,
 * 붙고 나면 진짜 값이다. `{{...}}` 도 `undefined` 도 찍힐 길이 없다.
 *
 * 의존 방향은 한쪽이다 — `types` ← `기본값` ← `용도` ← `model디자인틀`.
 */


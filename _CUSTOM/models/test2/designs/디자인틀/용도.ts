export interface i용도정의 {
  /**
   * 지금 이 편집기에서 다루는 용도인가. **끄면 화면에서만 사라진다** —
   * 어휘도 구도지시(`app/components/PrintTemplate/생성지시문.ts`)도 그대로 남고, 저장소의 그 용도 행들도 지워지지 않는다.
   *
   * 등급증 하나를 끝까지 파는 동안 나머지 둘이 목록에 서 있으면, 셋 다 반쯤 된 상태로
   * 어느 것이 기준인지 흐려진다. 되살릴 때 고칠 곳이 이 한 줄이어야 해서 플래그로 둔다 —
   * 코드를 지웠다가 다시 쓰면 그 사이에 바뀐 어휘가 같이 돌아오지 못한다.
   */
  show: boolean
  /**
   * 이 용도가 아는 자리 이름의 어휘. **용도마다 다르다** — 명함은 이름·직위·기관명,
   * 등급증은 등급·회원번호·수령인.
   *
   * 값을 대는 목록이 아니라 **이름과 예시**의 목록이다. 상자의 꼬리표가 여기 있는 키와 맞으면
   * 그 자리의 예시(`i변수.샘플`)를 빌려 쓸 수 있고, 안 맞으면 `자리현황()` 이 잡아낸다.
   */
  변수s: i변수[]
  /**
   * 이 양식이 요구하는 **이미지** 칸 (로고·사진·QR).
   *
   * 글자 변수와 나눠 둔 이유: 값이 URL 이라 `{{로고}}` 로 치환하면 종이에 주소가 인쇄된다.
   * 이건 표식 레이어가 받아야 하는데 `i표식` 에 아직 바인딩 필드가 없다 — 그래서 지금은
   * "이 양식이 무엇을 요구하는가"만 선언해 두고, 표식 바인딩이 붙으면 이 목록이 그 입력이 된다.
   */
  이미지s: string[]
  /**
   * 한 번 만들어 그대로 쓰는가(`한장`), 대상마다 값을 갈아끼워 N장을 뽑는가(`대상별`).
   *
   * 자리에 사람 축 값이 있는지와는 별개다 — 포스터도 주최·문의는 조직에서 올 값이다.
   * 이 축이 정하는 건 "회원을 N명 골라 N장을 뽑는가"뿐이다. 실값을 이을 때 쓸 선언이고,
   * 지금은 디자인틀목록 패널이 한 줄로 보여 주기만 한다.
   */
  발급단위: '한장' | '대상별'
}


/*
 * 글자 상자는 `{{키}}` 도 값도 들지 않는다. 상자는 전부 평등하고 다른 것은 좌표뿐이며,
 * 상자가 드는 것은 **꼬리표 하나**("이 자리는 이름 자리")와 **예시 하나**("여기엔 홍길동 같은 게
 * 들어온다")뿐이다. 종이에 나가는 글자는 언제나 `i글자.내용` 이고, 그건 편집 화면에서 사람이
 * 보고 있던 바로 그 글자다.
 *
 * 아래 함수들은 값을 만들지 않는다. 디자인틀에 붙은 꼬리표를 용도의 어휘와 맞대어 볼 뿐이다.
 */

/** 이 꼬리표를 아는 변수. `null` 이면 이 용도의 어휘에 없는 이름이다 */
export const 꼬리표변수 = (용도: i용도, 꼬리표: string): i변수 | null =>
  용도정의s[용도].변수s.find(v => v.키 === 꼬리표) ?? null

/**
 * 디자인틀이 실제로 쓰는 꼬리표. 면·상자 순서 그대로이고 중복은 접는다.
 *
 * 목록을 따로 들지 않는 이유는 예전과 같다 — 상자에 붙은 꼬리표가 유일한 근거여야
 * "목록엔 있는데 상자는 없는" 상태가 생기지 않는다.
 */
export function 꼬리표s(틀: i틀): string[] {
  const 본것 = new Set<string>()
  const 목록: string[] = []
  for (const 면 of 틀.면s) {
    for (const g of 면.글자s) {
      const h = g.꼬리표?.trim()
      if (h && !본것.has(h)) {
        본것.add(h)
        목록.push(h)
      }
    }
  }
  return 목록
}

/** 꼬리표가 붙은 자리 하나. 실값 층이 없으니 알 수 있는 건 이름과 개수뿐이다 */
export interface i자리 {
  꼬리표: string
  /** 이 용도의 어휘에 있는 이름인가. `null` 이면 사람이 직접 지은 이름이거나 오타다 */
  변수: i변수 | null
  /** 이 꼬리표를 쓰는 상자 수 */
  상자수: number
}

export function 자리현황(틀: i틀): i자리[] {
  const 수 = new Map<string, number>()
  for (const 면 of 틀.면s) {
    for (const g of 면.글자s) {
      const h = g.꼬리표?.trim()
      if (h) 수.set(h, (수.get(h) ?? 0) + 1)
    }
  }

  return 꼬리표s(틀).map(꼬리표 => ({
    꼬리표,
    변수: 꼬리표변수(틀.용도, 꼬리표),
    상자수: 수.get(꼬리표) ?? 0
  }))
}

/**
 * 용도가 모르는 이름이 붙은 자리. 대개 오타다 (`행사장소` 를 `장소` 라 적은 상자).
 *
 * 발급하면 맨 먼저 비는 자리가 여기다 — 주입 표(`model회원.디자인틀주입`)는 이 어휘의 이름으로
 * 값을 대므로, 어휘에 없는 이름은 닿을 값이 아예 없어 종이에서 빈칸으로 나온다.
 */
export const 모르는자리s = (현황: i자리[]) => 현황.filter(x => !x.변수)

/** 이 용도가 필수라고 정한 자리인데 디자인틀 어디에도 그 꼬리표가 없다 */

/**
 * 종이 **한 면**. 3개 레이어의 한 벌이다.
 *
 * 규격은 여기 없다 — 앞뒤 크기가 다른 인쇄물은 없으므로 디자인틀이 하나만 든다.
 * 배경 묘사는 면마다 다르다(앞은 회백색 종이, 뒤는 먹색) 그래서 `i배경` 이 면 안에 있다.
 */
export interface i면 {
  /** '앞' · '뒤'. 화면 라벨이자 인쇄 순서다 */
  라벨: string
  배경: i배경
  표식s: i표식[]
  글자s: i글자[]
}

/**
 * **디자인틀 한 벌.** 지금 캔버스에 열려 있는 그것이고, 저장되는 단위도 이것이다.
 *
 * 한때 이 자리에 "문서"가 있었다 — 디자인틀에서 뽑아 나와 따로 사는 한 장. 그런 층은 실제로
 * 없었다. 저장하는 코드도 불러오는 코드도 디자인틀 표 하나뿐이었고, 저장 행은 이 모양에서
 * `createdAt` 하나만 더 든 것이라 둘은 같은 것이었다. 그런데도 이름을 둘로 두는 바람에
 * 캔버스 위엔 `새 등급증_1`, 목록엔 `등급증_1` 이 따로 떴고, 디자인틀바는 디자인틀 자체를
 * 고치는 중에 `등급증_1 에서 고침` 이라고 적었다. 사본이 아닌 것을 사본이라 부른 탓이다.
 *
 * 그래서 이름도 하나, id 도 하나다. 캔버스에서 고치는 것이 곧 그 디자인틀이다.
 * (문서를 디자인틀과 별개로 저장할 일이 생기면 그때 표를 하나 더 두면 된다. 지금은 없다)
 *
 * 면이 몇 개인지는 `면s.length` 가 유일한 근거다 — `is양면형` 같은 불리언을 따로 들면
 * "양면이라는데 뒷면이 없는" 상태가 표현 가능해지고, 그때부터 화면·인쇄·검사가 저마다
 * 다른 답을 낸다. 길이 1이면 한 면, 2면 두 면 — **상한은 2다** (캔버스가 그 이상 못 만든다).
 * 배열인 건 N면을 위해서가 아니라 앞뒤 분기를 없애려는 것뿐이다.
 *
 * 다만 `양면` 이라는 말은 이 필드가 대신할 수 없다. `면s.length === 2` 는 "면이 둘"이라고만
 * 하지 **그 둘이 종이 한 장의 앞뒤인지, 종이 두 장인지**는 말하지 않는다 — 양면 명함과
 * 2쪽 학습지가 똑같이 2다. 나중에 인쇄를 붙이면 그 구분을 담을 `is양면` 이 따로 필요할 수 있다.
 * 위에서 경계한 불리언과는 역할이 다르다: 그건 면 개수의 근거가 되려 해서 문제였고,
 * 이건 개수를 안 정하고 장수만 말한다.
 */
export interface i틀 {
  /**
   * 저장소가 매긴 id. **아직 한 번도 저장하지 않았으면 빈 문자열**이고,
   * 그것이 "새 디자인틀"과 "저장된 디자인틀"을 가르는 유일한 표시다.
   *
   * 이름과 따로 있는 이유는 그대로다 — 이름을 고쳐도 같은 디자인틀이어야 한다.
   */
  id: string
  /** 목록에도 캔버스 위에도 이 이름 하나가 뜬다 */
  이름: string
  /** 이 디자인틀이 아는 자리 어휘 (`용도.ts` 의 `용도정의s`). 꼬리표를 맞대어 볼 때 쓴다 */
  용도: i용도
  규격: i규격
  면s: i면[]
}

/**
 * 디자인틀 — 인쇄물 한 벌의 **모양**. 표 `design-templates` 에 앉는 행의 속살이다.
 *
 * 편집기가 잡고 있는 상태(`i선택`)와 캔버스가 재서 넣는 실측(`i글자실측`)은 여기 없다 —
 * 그건 화면의 것이라 `app/components/PrintTemplate/편집타입.ts` 가 든다. 여기 있는 것은 저장되는 것뿐이다.
 *
 * 등급증·포스터·명함처럼 "배경 그림 위에 표식과 글자를 얹는" 출력물을 3개 레이어로만 기술한다.
 *
 *   1. 배경이미지 — 데이터가 없는 그림 면 (AI 생성 or 업로드). 종이의 지질과 **테두리 문양까지** 한 장이다
 *   2. 표식       — 로고·리본·도장·봉인처럼 글자가 아닌 낱장 그림, 그리고 단색 **색판**
 *   3. 글자     — 사각형 안에 들어가는 텍스트
 *
 * 레이어 순서는 이 정의 자체가 정한다 (배경 → 표식 → 글자). 그래서 z-index 필드가 없다.
 *
 * **테두리가 레이어였던 적이 있다.** 배경이 상류 비율 enum(A4 = 1:1.414 없음)에 맞춰 생성되던
 * 시절엔 규격을 갈 때마다 배경이 cover 로 잘려 가장자리 문양부터 사라졌고, 그래서 규격과 무관하게
 * 사방 여백으로 사는 별도 레이어가 필요했다. 지금은 배경이 규격 그대로 생성되고(`i배경.비율`)
 * 어긋나면 다시 뽑기를 권하므로, 그 레이어가 있을 이유가 없어져 걷어냈다.
 * 같은 레이어 안에서는 배열 순서가 곧 그리는 순서다.
 *
 * 실값(회원·강좌 데이터)을 잇는 층은 아직 없다. 상자는 꼬리표로 자기가 무슨 자리인지 말하고
 * 예시로 무엇이 들어올지 보여줄 뿐, 그 값을 가져오는 코드는 어디에도 없다 — 디자인틀을 먼저
 * 짜는 단계라서다. 그래서 화면에 뜨는 글자가 곧 종이에 나가는 글자다.
 *
 * 좌표 규칙(x·w 는 문서 폭 대비 %, y·h 는 높이 대비 %)은 폐기된 카드 좌표계에서 그대로
 * 가져왔다 — 거기서 이미 검증된 규칙이라 새로 정할 이유가 없었다.
 */

import type { i틀서체 } from '../서체'


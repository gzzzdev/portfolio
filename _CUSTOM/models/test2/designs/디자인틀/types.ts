/* 2. 표식 레이어 (로고 · 리본 · 도장 · 봉인)                           */
/* ------------------------------------------------------------------ */

/**
 * 표식 1개. **글자가 아닌 면**이면 전부 이것이다 —
 * 가운데 옅게 깔리는 로고, 우측 상단 리본, 인주 도장, 봉인 왁스, 그리고 색만 칠한 색판(`채움`).
 *
 * 이 자리 이름이 `씰` 이었다. 도장 하나만 놓던 시절의 이름인데, 실제로 놓이는 것은 그보다
 * 넓었다 — 리본을 씰이라 부를 수는 없다. 이름이 좁으면 놓을 수 있는 것까지 좁아 보이므로
 * (원형 목록에는 이미 `금박 리본` 이 있었는데도 자리 이름은 계속 도장이었다) 자리를 그
 * 자리가 하는 일로 다시 불렀다.
 *
 * **종류를 나누지 않는다.** 로고든 도장이든 이 층이 하는 일은 하나다 — 사각형에 놓고,
 * 돌리고, 투명도와 합성을 정한다. `종류` 필드를 들면 렌더에는 아무 차이도 안 나면서
 * "리본인데 곱하기로 놓았다"를 틀렸다고 말할 근거만 생긴다.
 *
 * 글자 레이어와 나눠 둔 이유: 표식은 **비율을 지켜야 하고 회전하며 곱하기 합성**을 쓴다.
 * (붉은 인주 도장을 종이 위에 얹을 때 `multiply` 가 아니면 스티커처럼 뜬다.)
 * 텍스트 규칙(줄바꿈·크기 축소)은 여기에 하나도 필요 없다.
 */
export interface i표식 {
  id: string
  rect: iRect
  url: string | null
  /** 이 그림을 만든 문장. 배경의 `묘사`와 같은 역할 */
  묘사: string
  /**
   * 이 자리가 무슨 자리인가. 글자 상자의 `꼬리표` 와 **같은 규칙의 자유 문자열**이다 —
   * 용도의 이미지 어휘(`i용도정의.이미지s`)와 맞으면 그 값이 주입되고, 어긋나면 안 들어온다.
   *
   * 이 칸이 없던 동안 QR·엠블럼·회원사진은 디자인틀로 들어올 길이 아예 없었다. 값이 URL 이라
   * 글자 상자에 넣으면 종이에 주소가 인쇄되고(`i용도정의.이미지s` 머리말), 표식에는 받을 칸이
   * 없었기 때문이다. 그래서 `용도.ts` 가 "이 양식은 QR 을 요구한다"고 **선언만** 해 두고
   * 실제로 잇지는 못했다. 이 한 칸이 그 선언의 상대편이다.
   *
   * **무엇이 들어오는지는 이 칸이 정하지 않는다.** 그림 링크인지 QR 문자열인지는 값을 대는
   * 쪽(`i주입그림`)이 말한다 — 표식에 `종류` 를 두지 않는 이유(위 머리말)가 여기서도 같다.
   * 비어 있으면 아무것도 주입되지 않는, 그냥 얹어 둔 그림이다.
   */
  꼬리표?: string
  /**
   * **색판** — 그림이 없을 때 이 사각형을 채우는 단색 (`#rrggbb`).
   *
   * 회원증 윗단의 남색 판처럼 "그림이 아니라 색이 칠해진 면"을 위한 칸이다. 그런 면을
   * 그릴 방법이 없어서 회원증만 오래 코드 렌더러로 남아 있었다 — 배경은 면당
   * 한 장뿐이고 글자 상자에는 배경색이 없다.
   *
   * **레이어를 새로 만들지 않은 이유**: 색판이 하는 일이 표식과 같기 때문이다. 사각형에
   * 놓이고, 돌고, 투명해지고, 곱하기로 섞인다. 레이어를 하나 더 두면 그리는 순서가 넷이
   * 되고(배경 → 색판 → 표식 → 글자) "색판 위의 도장"은 되는데 "도장 위의 색판"은 안 되는,
   * 근거 없는 제약이 생긴다. 같은 층에 두면 배열 순서가 그 답을 그대로 준다.
   *
   * 곱하기 합성과 만나면 **틴트**가 된다 — 종이 결을 살린 채 한쪽을 물들인다.
   * `url` 이 있으면 이 값은 무시된다: 한 사각형이 그림이면서 색판일 수는 없다.
   */
  채움?: string | null
  /**
   * 그림이 상자를 채우는 방식. 없으면 `맞추기`(`contain`).
   *
   * 로고·도장은 비율이 깨지면 안 되므로 기본이 맞추기지만, **인물 사진은 잘라야 한다** —
   * 증명사진을 맞추기로 넣으면 상자 안에서 레터박스가 생긴다. `채우기` 는 위쪽을 기준으로
   * 자른다(`objectPosition: center top`): 사람을 자를 때 남겨야 하는 쪽은 늘 얼굴이다.
   */
  맞춤?: i표식맞춤
  /** 시계방향 각도. 손으로 찍은 도장 느낌은 2~5도에서 난다. 범위는 ±`표식회전한계` */
  회전: number
  /** 0~1 */
  불투명도: number
  /** 배경과 섞는 방식. 인주 도장은 '곱하기' */
  합성: i표식합성
}

/**
 * 표식이 돌 수 있는 최대 각(도). 캔버스 손잡이와 패널 슬라이더가 **같은 값을 봐야 한다** —
 * 한쪽만 넓으면 거기서 돌려 둔 각이 다른 쪽을 건드리는 순간 끌려온다.
 *
 * 한 바퀴를 다 돌 이유가 없어서 이만큼이다. 종이에 얹는 그림이 쓰는 각은 0도 언저리이거나
 * 살짝 기운 정도고, 거꾸로 뒤집힌 로고·도장은 실수지 디자인이 아니다.
 *
 * **모서리 리본의 45도는 이 값이 지지 않는다.** 우측 상단을 가로지르는 리본은 원형
 * (`표식원형s` 의 `모서리리본`)이 프레임 안에 이미 기울여 그려 온다 — 45도가 그림의 일부라
 * 얹은 뒤에 돌릴 것이 없다. 여기 회전은 그렇게 만들어진 표식을 손으로 조금 비트는 몫만 진다.
 * 그러니 한계를 45로 올릴 이유도 없다: 그건 리본을 여기서 돌리게 하려던 값인데, 그러면
 * 리본 그림 하나가 45도로 두 번 돈다.
 */
export const 표식회전한계 = 30

export const 표식합성s = ['보통', '곱하기'] as const
export type i표식합성 = (typeof 표식합성s)[number]

/**
 * 그림이 상자를 채우는 방식. 배경의 `배경맞춤s` 와 어휘를 맞추되 `늘이기` 는 없다 —
 * 배경은 종이 전체라 비율을 눌러서라도 덮어야 할 때가 있지만, 표식은 로고·도장·사진이라
 * 비율이 깨진 순간 그냥 잘못 놓인 그림이다.
 */
export const 표식맞춤s = ['맞추기', '채우기'] as const
export type i표식맞춤 = (typeof 표식맞춤s)[number]


/* 3. 글자 레이어                                                      */
/* ------------------------------------------------------------------ */

/**
 * 글자 상자 1개.
 *
 * **상자에 등급이 없다.** '고정문구 상자'와 '변수 상자'로 나뉘지 않는다 — 전부 같은 글자 상자고
 * 다른 것은 좌표(`rect`)와 글자 모양뿐이다. 다만 상자마다 `꼬리표` 를 하나 달 수 있고,
 * 글루코드(`용도.ts`)가 그 이름을 보고 데이터를 이어 준다.
 *
 * 상자는 고정이고 글자가 그 안에서 줄어든다 — 값이 길어져도 옆 상자를 밀지 않는다.
 */
export interface i글자 {
  id: string
  rect: iRect
  /**
   * **바깥에서 주입받는 글자.** 이 상자에 앉을 진짜 값이다.
   *
   * 자리 상자(`용도.ts` 의 `자리`)는 이 칸을 **비운 채로** 깔린다 — 주입할 데이터가 아직
   * 없어서다. 그동안 화면에 뜨는 건 `예시` 고, 주입이 붙으면 이 칸이 채워지면서 예시를 덮는다.
   * 렌더는 `내용 || 예시` 한 줄뿐이라 상자가 무엇을 보여줄지에 다른 규칙이 끼어들 자리가 없다.
   *
   * 고정문구 상자는 반대다 — 주입받을 것이 없으니 여기 적힌 글자가 처음부터 최종 문구다.
   * 그래서 고정문구에는 예시가 없고, 자리 상자에는 (아직) 내용이 없다.
   */
  내용: string
  /**
   * `내용` 이 주입되기 전까지 그 자리에 **대신 보이는** 글자. 주입되면 가려진다.
   *
   * 두 몫을 한다. 값이 없는 동안 자리 상자가 빈 채로 떠서 배치를 못 읽게 되는 걸 막고,
   * 디자인틀을 짜는 사람에게 "여기엔 이런 게 들어온다"를 **실제 길이로** 보여 준다 —
   * `증명문구` 네 글자와 두 줄짜리 실제 문장은 상자 높이·줄간격이 전혀 다르다.
   *
   * 한때 자리 상자의 `내용` 에 꼬리표를 그대로 박아 이 몫을 흉내 냈다. 예시가 생긴 지금
   * 그건 남아 있을 이유가 없다 — 꼬리표는 자리의 **이름**이지 그 자리에 들어올 값이 아니다.
   *
   * `i변수.샘플` 과 겹쳐 보이지만 층이 다르다. 샘플은 **용도**가 아는 예시라 `꼬리표` 가
   * 그 용도의 변수와 이름이 맞을 때만 닿는다 — 꼬리표는 자유 문자열이므로(`행사장소` 를 `장소` 라
   * 적은 상자) 닿지 않는 자리가 반드시 생긴다. 이건 **상자**가 자기 몫으로 드는 예시고,
   * 비어 있으면 패널이 용도의 샘플을 자리표시로 빌린다.
   */
  예시?: string
  /**
   * 이 자리가 무슨 자리인가. **자유 문자열**이다.
   *
   * 용도의 어휘(`i변수.키`)와 같을 필요가 없다 — 맞으면 그 자리의 라벨·예시를 빌려 쓰고,
   * 어긋나면 `자리현황()` 이 "용도가 모르는 이름"으로 잡아 준다. 막지는 않는다.
   * 비어 있으면 아무것도 들어올 자리가 아니라는 뜻, 즉 고정문구다.
   */
  꼬리표?: string
  /** 글자 크기 상한 (문서 **폭** 대비 %). 넘치면 렌더러가 이 아래로 줄인다 */
  크기: number
  /** `#rrggbb` */
  색: string
  /**
   * 서체. 이미 로드된 스택(`서체스택`)을 그대로 쓴다 —
   * 폰트 목록을 여기서 새로 만들면 CSS 변수와 두 벌이 되어 반드시 어긋난다.
   */
  서체: i틀서체
  /**
   * 굵기. 두 단계뿐인 건 서체가 그 이상을 못 받아 주기 때문이다 — 신라·솔뫼·조선명조는
   * 웨이트 서술자 없는 단일 woff 라(`mTheme.css`) 400 하나로 잡히고, 그 위는 전부
   * 브라우저 합성 볼드로 같아진다. 400/600/800 세 칸을 두면 UI만 세 칸이고 종이는 두 칸이었다.
   */
  굵기: i굵기
  정렬: i정렬
  세로정렬: i세로정렬
  /** 세로쓰기 (증서·호패). 글자 수에 맞춰 크기가 더 줄어든다 */
  세로쓰기: boolean
  /** 줄 간격 배수 */
  줄간격: number
}


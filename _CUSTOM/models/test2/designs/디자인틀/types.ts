export const 세로정렬s = ['위', '가운데', '아래'] as const
export const 굵기s = ['보통', '굵게'] as const

export type i정렬 = (typeof 정렬s)[number]
export type i세로정렬 = (typeof 세로정렬s)[number]
export type i굵기 = (typeof 굵기s)[number]


/* 용도 · 주입 변수                                                    */
/* ------------------------------------------------------------------ */

/**
 * 디자인틀의 용도. 어떤 자리 이름을 쓸 수 있고 어떤 고정문구로 시작하는지가 여기서 갈린다.
 * 실제 목록·레이아웃은 `용도.ts` 가 갖는다 — 여기는 갈래 이름만 닫아 둔다.
 */
export const 용도s = ['등급증', '행사포스터', '명함', '회원증'] as const
export type i용도 = (typeof 용도s)[number]

/**
 * 이 용도가 아는 자리 이름 하나. **값이 아니라 어휘다.**
 *
 * 값을 대는 필드(`출처`·`조립`)가 한때 있었지만 실값 층을 통째로 걷어내면서 같이 지웠다
 * (`용도.ts` 머리말). 남은 것은 이름과 예시뿐이고, 그 둘이 디자인틀을 짜는 데 필요한 전부다.
 *
 * 여기 있는 것은 "이 용도에 놓을 수 있는 자리"일 뿐, 디자인틀이 실제로 쓰는지와는 별개다.
 * 실사용의 유일한 근거는 상자에 붙은 `i글자.꼬리표` 이고, `자리현황()` 이 둘을 맞대어 본다.
 */
export interface i변수 {
  /** 상자의 `꼬리표` 로 적는 이름. 이 용도 안에서의 이름이다 */
  키: string
  /** 패널에 보이는 이름. 키가 짧아도 뜻이 서게 한다 */
  라벨: string
  /**
   * 이 자리에 어떤 값이 들어오는지 보여주는 예시. 실제 길이로 적는다.
   *
   * 상자가 자기 예시(`i글자.예시`)를 안 들 때 패널이 이걸 자리표시로 빌린다 —
   * 꼬리표가 이 `키` 와 맞을 때만 닿으므로, 상자 쪽 예시를 대신하지는 못한다.
   */
  샘플: string
  /** 이 자리 없이 발급하면 인쇄물이 성립하지 않는다 */
  필수?: boolean
}


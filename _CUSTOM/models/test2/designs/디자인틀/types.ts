/**
 * 배경 이미지 1장.
 *
 * `url` 은 생성/업로드 결과, `묘사` 는 그 그림을 만든 문장이다.
 * 묘사를 같이 들고 있어야 "같은 결로 다시 뽑기"가 되고, 템플릿을 저장했을 때
 * 왜 이 그림인지가 남는다. 아직 안 만들었으면 `url` 은 null 이고 `바탕색`만 보인다.
 */
export interface i배경 {
  url: string | null
  묘사: string
  /**
   * 이 그림을 만들 때의 문서 비율(폭/높이). 아직 없거나 밖에서 받은 그림이면 null.
   *
   * **배경만 규격에 종속된 레이어라서 이 값이 필요하다.** 글자·표식은 % 좌표라 규격을 갈아도
   * 제자리를 지킨다. 배경만은 그 비율에
   * 맞춰 생성된 **픽셀**이라, 규격이 바뀌면 잘리거나 늘어나는 것 말고 할 수 있는 일이 없다.
   * 그래서 "언제 어긋났는지"를 그림 스스로 들고 있어야 한다 — 0단계가 그걸 읽어 다시 뽑기를 권한다.
   */
  비율: number | null
  /** 문서 비율과 이미지 비율이 다를 때: 채우기(잘림) vs 맞추기(여백) */
  맞춤: i배경맞춤
  /** 0~1. 글자가 묻힐 때 배경을 죽인다 */
  불투명도: number
  /** 이미지 아래에 깔리는 색. 이미지가 없거나 `맞춤: '맞추기'` 여백에 보인다 */
  바탕색: string
}

export const 배경맞춤s = ['채우기', '맞추기', '늘이기'] as const
export type i배경맞춤 = (typeof 배경맞춤s)[number]


/* ------------------------------------------------------------------ */

/**
 * 사각형 1개. 표식과 글자가 공유하는 유일한 위치 표현.
 *
 * x·w 는 **문서 폭** 대비 %, y·h 는 **문서 높이** 대비 % (CSS absolute 와 같은 규칙).
 * 픽셀을 쓰지 않는 이유: 화면 미리보기와 300dpi 인쇄가 같은 값으로 렌더돼야 한다.
 */
export interface iRect {
  x: number
  y: number
  w: number
  h: number
}

/** 인쇄물 실물 규격. mm 를 갖고 있어야 인쇄 픽셀(dpi)을 역산할 수 있다. */
export interface i규격 {
  /**
   * 규격 자체의 이름 — `A4 세로`, `카드 가로`. 종이를 고르는 자리에서 1차로 읽히는 값이다.
   *
   * '상장'·'증서' 같은 쓰임새는 여기 넣지 않는다. 그건 이 종이로 만들 수 있는 것 중 하나일 뿐
   * 규격의 정체가 아니고 (A4 세로는 증서도 되고 안내문도 된다), 무엇을 만들지는 이미
   * 디자인틀이 고른다. 쓰임새는 `비고` 로 내려간다.
   */
  이름: string
  /** 이 크기가 보통 무엇에 쓰이는지. 고르는 데 도움만 주는 곁줄이다 */
  비고?: string
  폭mm: number
  높이mm: number
}


/**
 * 면 한 벌을 그대로 복제하되 **id 만 새로 낸다**. 저장된 디자인틀을 캔버스에 열 때 쓴다.
 *
 * 저장된 배치는 JSON 한 벌이라 그대로 물리면 같은 id 를 든 상자가 두 곳에 서고,
 * 선택(`i선택`)도 실측(`글자실측키`)도 둘을 못 가른다.
 *
 * 깊게 뜨는 이유는 따로다. 얕게 물리면 캔버스에서 상자를 끌 때 목록에 앉아 있는 행의 `rect`
 * 가 같이 움직여, 저장하지도 않은 변경이 목록에 비친다.
 */
export function 면s복제(면s: i면[]): i면[] {
  return 면s.map(면 => ({
    ...면,
    배경: { ...면.배경 },
    표식s: 면.표식s.map(s => ({ ...s, id: uid('s'), rect: { ...s.rect } })),
    글자s: 면.글자s.map(g => ({ ...g, id: uid('t'), rect: { ...g.rect } }))
  }))
}

/**
 * 아직 저장한 적 없는 새 디자인틀. 흰 A4 한 장이 전부다.
 *
 * 두 자리에서 쓴다 — 편집기가 처음 뜰 때(목록이 브라우저에서 뒤늦게 도착하므로 그 사이에
 * `i틀` 은 무엇이든 들고 있어야 한다), 그리고 디자인틀목록의 '새로 만들기'.
 *
 * `id: ''` 가 "아직 저장 안 됨"의 유일한 표현이다. 없는 id 를 넣어 두면 지워진 디자인틀을
 * 가리키는 상태와 구별되지 않는데, 그 둘은 사람에게 할 말이 다르다.
 */
export function 빈디자인틀(): i틀 {
  return {
    id: '',
    이름: '새 디자인틀',
    // 아직 뜻이 정해지지 않았다. 첫 갈래를 두는 건 `i용도` 가 닫힌 집합이라 빈 값이 없어서다
    용도: 용도s[0],
    규격: { ...규격s.A4세로 },
    면s: [새면('앞')]
  }
}

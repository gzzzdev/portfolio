/** 규격 셀렉트 목록. 용도가 규격을 정해 주긴 하지만 사용자가 바꿀 수 있다 */
export const 규격프리셋s: i규격[] = Object.values(규격s)

/** 300dpi 인쇄에 필요한 픽셀 폭. 미리보기 폭으로 캡처하면 A4가 뭉갠다 */
export const 인쇄폭 = (규격: i규격, dpi = 300) => Math.round((규격.폭mm / 25.4) * dpi)

/**
 * 화면 미리보기 폭(px). 인쇄 폭(A4 = 2480px)으로 모달에 띄우면 화면 밖으로 나간다.
 *
 * 종이 **모양**에 따라 가른다 — 세로로 긴 증서는 좁게, 가로로 긴 명함은 넓게 잡아야
 * 둘 다 모달 안에서 비슷한 크기로 보인다. 폭 하나만 정하면 세로 A4 는 모달을 넘고
 * 가로 명함은 우표만 해진다. (모달의 `orientation` 도 같은 기준으로 갈린다)
 */
export const 미리보기폭 = (규격: i규격) => (규격.폭mm > 규격.높이mm ? 640 : 420)

/**
 * 빈 면 1장. 그림은 아직 없고 "어떤 그림이어야 하는가"(묘사)만 들고 시작한다.
 * 면마다 배경이 따로라 이 함수도 면 단위다 — 앞은 회백색 종이, 뒤는 먹색일 수 있다.
 */
export function 새면(라벨: string, 묘사 = ''): i면 {
  return {
    라벨,
    배경: {
      url: null,
      묘사,
      비율: null,
      맞춤: '채우기',
      불투명도: 1,
      바탕색: '#ffffff'
    },
    표식s: [],
    글자s: []
  }
}

let 일련번호 = 0
const uid = (접두: string) => `${접두}${Date.now().toString(36)}${(일련번호++).toString(36)}`
/**
 * 새 상자를 놓을 자리. 시작 자리가 이미 차 있으면 계단식으로 비켜 놓는다.
 *
 * 캔버스가 유일한 picker 가 된 뒤로 **완전히 겹친 상자는 밑에 깔린 쪽을 클릭으로 꺼낼 수 없다**
 * (Tab 순회가 최후의 탈출구지만, 애초에 겹치지 않게 놓는 편이 낫다).
 * 개수가 아니라 실제 좌표로 비교한다 — 셋을 만들고 둘을 지우면 개수는 다시 1 이 되지만
 * 남은 하나가 어느 자리를 쓰는지는 개수가 모른다.
 */
export function 빈자리(기존: iRect[], 시작: iRect): iRect {
  const 계단 = 3
  for (let k = 0; k < 12; k++) {
    const x = 시작.x + k * 계단
    const y = 시작.y + k * 계단
    // 종이 밖으로 밀려나느니 겹치는 게 낫다 — 밖은 손으로 끌어 낼 자리지(도련),
    // 새 상자가 처음부터 반쯤 나가 앉을 자리가 아니다
    if (x + 시작.w > 100 || y + 시작.h > 100) break
    if (!기존.some(r => Math.abs(r.x - x) < 1 && Math.abs(r.y - y) < 1)) return { ...시작, x, y }
  }
  return { ...시작 }
}


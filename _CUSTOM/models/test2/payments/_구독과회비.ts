/**
 * 구독과 회비 — 무엇이 아직 안 정해졌나.
 *
 * 여기 코드가 없다. `payments/`의 세 모델(`model회비` · `model회원회비` · `model결제`)이
 * 무슨 축 위에 서 있는지, 그중 어디가 아직 아리까리한지를 적어둔 파일이다. test1의
 * `model정기회비`를 지우면서 그쪽에만 있던 판단 규칙이 같이 사라지길래 여기로 옮겨 적는다.
 *
 * ────────────────────────────────────────────────────────
 * ## 축이 둘이고, 둘은 다른 질문에 답한다
 *
 *   · **구독** — "이 사람이 지금 유효한가." 소유자는 `model등급`이다
 *     (`구독구분: FREE | ANNUAL | LIFETIME`, `알림일수`, `유예일수`). 등급이 곧 상품이고,
 *     사람에게 붙는 건 기간이다.
 *   · **회비** — "얼마를 청구했고 받았나." `model회비`가 청구 상품
 *     (`청구유형: ADMISSION 입회비 | REGULAR 기간회비 | MATERIAL 기타`),
 *     `model회원회비`가 회원×청구 한 줄, `model결제`가 토스 트랜잭션 한 건.
 *
 * 이 둘을 한 축으로 접으려던 흔적이 지금 코드 곳곳의 어긋남이다. 아래 다섯이 그것.
 *
 * ────────────────────────────────────────────────────────
 * ## 1. `model회원회비`가 두 일을 겸한다
 *
 * 한 행이 청구서(`paidAmount` · `paymentId` · `paidAt`)이면서 동시에 자격 기간
 * (`startDate` · `endDate` · `alertDays` · `graceDays`)이다. 그래서 납부 행을 지우면
 * 그 사람의 유효기간도 같이 사라지고, 면제(EXEMPT)나 관리자 수기 연장처럼 **돈이 안 움직이는
 * 자격 변동**을 적을 자리가 없다. `is회비완납 = is유효 && is결제완료`가 둘을 곱해서 덮고 있을 뿐이다.
 *
 * 가르려면 회원×기간(자격) 행과 청구×납부 행이 따로 서고 후자가 전자를 가리켜야 한다.
 * 안 가르려면 "돈 없는 자격 변동"을 어떻게 적을지부터 정해야 한다. 지금은 어느 쪽도 아니다.
 *
 * ## 2. 유예·알림 일수가 두 군데에 있고 소유자가 없다
 *
 * `model등급.알림일수/유예일수`와 `model회원회비.alertDays/graceDays`가 같은 값이다.
 * 등급이 정책이고 회원회비가 발급 시점 스냅샷이라면 복제가 맞다 — 정책을 바꿔도 이미 발급된
 * 기간이 흔들리면 안 되니까. 그런데 **스냅샷을 뜨는 코드가 없다.** 회원회비 쪽은 그냥
 * `?? 7` · `?? 3` 기본값으로 서 있고 등급을 쳐다보지 않는다. 복제인지 우연히 같은 숫자인지가
 * 코드에 안 적혀 있는 상태다.
 *
 * ## 3. 상태 축이 셋인데 하나는 남의 어휘를 쓴다
 *
 *   · `i회비유효상태` — NOT_STARTED · ACTIVE · EXPIRING_SOON · IN_GRACE · EXPIRED. **날짜**만 본다.
 *   · `i결제표시상태` — READY · PAID · FAILED · REFUNDED + UNSUBSCRIBED · EXEMPT. **돈**만 본다.
 *   · `i회비레거시상태`(`dynamicState`) — 둘을 섞어놨던 옛 축. SUBSCRIBED/UNSUBSCRIBED/
 *     FINALLY_EXPIRED가 한 줄에 있다. 지금은 `show: false`로 폼에서만 숨겨져 있고 살아는 있다.
 *
 * `UNSUBSCRIBED`가 문제다. 값이 뜻하는 건 **"결제 행이 아직 없다"**이지 "구독을 안 한다"가 아니다
 * (`model회원신청.결제상태`도 `this.신청결제?.결제상태 ?? 'UNSUBSCRIBED'`로 없음을 이 값으로 메운다).
 * 구독 어휘를 결제 축에 얹어둔 탓에, 화면에선 '미납부'로 뒤집어 읽고 있다. 일회성 신청 결제에까지
 * 구독 단어가 따라붙는 게 지금 제일 눈에 걸리는 지점.
 *
 * ## 4. 청구 소스가 둘이었고, 하나가 방금 끊겼다
 *
 * `i회원회비dto`에 부모 키가 둘이다 — `periodicFeeId`(정기회비 행)와 `feeId`(회비 상품 행).
 * `결제예상금액`이 정기회비 쪽이면 상수 `기간회비기본금액`(12,900)을 쓰고, 회비 상품 쪽이면
 * 그 상품의 `기본금액`을 쓴다. 즉 **같은 표의 두 행이 서로 다른 데서 금액을 얻어온다.**
 *
 * 정기회비(`model정기회비` · `periodic-fees`)는 test1에만 있었고 test2로 안 넘어왔다.
 * 이번에 test1을 지우면서 그 축은 완전히 끊긴다. `연결정기회비` 게터는 이미 부르면
 * `ReferenceError`였고(그래서 `getsBy정기회비`가 인스턴스가 아니라 id로 거른다), 이제
 * `periodicFeeId`는 아무도 안 채우는 死 컬럼이다. **정리하려면 `feeId` 한 축으로 모으고
 * `기간회비기본금액` 상수도 `model회비` 행의 `기본금액`으로 흡수해야 한다.**
 *
 * 다만 정기회비가 들고 있던 게 하나 있었다 — 청구 발행 시 **누가 납부 대상인가**의 판정이다.
 * 그 규칙만 옮겨 적는다(`is납부대상`):
 *
 *   기준월 = 청구 기준일의 그 달. 대상 조건 둘.
 *     ① 가입일 <= 기준월 말일 (그 달 안에 이미 회원이었을 것)
 *     ② 기준월 구간(가입일과 월초 중 늦은 쪽 ~ 월말) 동안 '잠자는' 상태 이력이 없을 것
 *        (`model회원상태이력s.잠자는중DuringPeriod`)
 *   즉 **월 중간 가입자는 그 달부터 대상, 월 중 한 번이라도 비활성이면 그 달은 제외**다.
 *   일할 계산은 없다 — 대상이거나 아니거나 둘 중 하나.
 *
 * 이 판정이 회비 청구를 발행할 때 다시 필요해지면 `model회비`(청구유형 REGULAR) 쪽에 얹으면 된다.
 *
 * ## 5. 기간모드 — 여기가 구독과 회비의 진짜 갈림길
 *
 * `i회원회비기간모드`에 다섯이 선언돼 있다:
 *   SUBSCRIPTION_YEAR · FISCAL_YEAR · FISCAL_Q2 · FISCAL_Q4 · FISCAL_Q12.
 *
 *   · `SUBSCRIPTION_YEAR` = **구독**. 결제일부터 1년. 사람마다 만료일이 다르다.
 *   · `FISCAL_*` = **회비**. 회계연도 시작~끝. 전원의 만료일이 같고, 언제 내든 그 해 말에 끝난다.
 *
 * 두 모델은 돈 계산이 다르다. 회계연도 방식은 11월 가입자가 두 달치에 1년 값을 내는 셈이라
 * 일할·감액 규칙이 따라붙어야 정상인데 지금은 없다. 구독 방식은 그 문제가 없는 대신
 * "올해 회비 낸 사람" 같은 단체 관점 집계가 안 나온다.
 *
 * 현재는 `static 기간모드 = 'FISCAL_Q12'`로 **코드에 박아둔 회비 모델**이다. 그리고
 * `get기본기간`의 분기는 `SUBSCRIPTION_YEAR` 하나뿐이라 **FISCAL_Q2 · Q4 · Q12는 전부
 * 같은 코드로 떨어진다** — 분기 이름만 있고 구현이 없다. 분기 단위 청구를 진짜로 할 거면
 * 여기부터 채워야 하고, 안 할 거면 세 값을 지우고 FISCAL_YEAR 하나로 줄이는 게 맞다.
 *
 * ────────────────────────────────────────────────────────
 * ## 이름에 대하여: 지금 '정기결제'는 정기결제가 아니다
 *
 * `runtimeConfig`에 토스 키가 있지만 `billingKey`는 어디에도 없다. 자동 재청구가 없다는 뜻이다.
 * 지금 흐름은 **관리자가 기간 청구를 발행 → 대상자를 일괄 등록 → 회원이 건별로 결제**다.
 * 정기적인 건 청구지 결제가 아니다. 진짜 recurring을 붙이려면 빌링키 보관·재시도·실패 후
 * 유예 처리가 새로 필요하고, 그때 위 1번(자격과 청구의 분리)이 선행조건이 된다 —
 * 자동결제 실패가 곧 자격 상실이 되면 안 되니까.
 *
 * ## 정할 때의 기준
 *
 * 단체 회비인지 개인 구독인지가 먼저다. **회비면** FISCAL 한 축으로 굳히고 `구독구분`을
 * 등급에서 떼거나 '유효기간 방식'으로 개명, 일할 규칙을 정한다. **구독이면**
 * `SUBSCRIPTION_YEAR`로 바꾸고 정기 청구 발행(위 4번의 대상자 판정)을 통째로 버린다.
 * 둘 다 필요하면 그때 `기간모드`가 static이 아니라 **등급별 설정**으로 내려가야 한다 —
 * 지금 하드코딩된 static 하나가 "아직 안 정했다"의 표시다.
 */

/**
 * `docs` 표의 초기데이터. **본문 md 는 여기서 안 적는다** — `~utils/mdc/samples` 의 `본문샘플s` 를 읽는다.
 *
 * ## 왜 시드가 뒤늦게 생겼나 (2026-09-07)
 *
 * `docs` 는 처음(2026-09-06)에 **json 을 손으로 부어** 만들었다. 그래서 `model문서s` 에만 `seed` 가
 * 비어 있었고, 표를 비우면 `do초기데이터` 가 「seed 데이터가 없습니다」로 끝났다 —
 * **되살릴 길이 없는 표**였다. 실제로 그 사이에 1001 행에는 편집기를 시험하며 친 낙서
 * (`::align` 두 덩이)가 들어가 그대로 커밋됐고, 되돌릴 곳이 없어 손으로 지워야 했다.
 * CLAUDE.md 가 localDB 를 두고 적은 「재생성이 필요하면 seeds 에서 다시 만든다」가
 * 이 표에만 갈 곳이 없었던 것이다. 이 파일이 그 자리다.
 *
 * ## 샘플에서 파생한다 — 사본이 아니다
 *
 * 같은 md 를 두 벌 두면 한쪽이 조용히 낡는다(`blocks.ts` 머리말의 「두 벌이 되는 순간」과 같은 규율).
 * 판(`/decisions/content/wysiwyg`)이 보는 것과 이 표에 부어지는 것이 **한 벌**이라야,
 * 샘플에 어휘를 하나 더 넣었을 때 표 쪽에서도 그게 실제로 저장·재열람되는지가 시험된다.
 *
 * **부어진 뒤에는 갈린다.** 시드는 목록이 비어 있을 때만 돌고(`BaseModels2.do초기데이터`),
 * 부어진 행은 처음 저장할 때 md 가 정규화된다(`m/Editor/md.vue`). 그건 사고가 아니라 그 정규화다.
 *
 * ## 샘플에서 안 가져오는 칸이 하나 있다
 *
 * `i본문샘플.설명` 은 **견본으로서의 설명**이다("절차·갈래·상태표가 섞인 가장 무거운 글 — 어휘가
 * 실제로 버티는지는 여기서 갈린다"). `i문서dto.summary` 는 **그 글 자체의 한 줄 요약**이라
 * 읽는 사람이 다르다. 그래서 요약만 여기서 적는다. 제목은 같은 말이라 샘플 쪽을 그대로 쓴다.
 *
 * `독자` 도 여기서 정한다 — 샘플의 `독자`("내부 스태프")는 사람에게 하는 말이고,
 * 이 표의 `reader` 는 `i문서독자options` 로 닫힌 값("스태프")이라 필터 축이 된다.
 */
const md = (key: string) => {
  const s = 본문샘플s.find(x => x.key === key)
  // 샘플의 `key` 가 바뀌면 조용히 빈 본문이 부어지는 대신 여기서 멈춘다.
  if (!s) throw new Error(`본문샘플 「${key}」를 찾을 수 없습니다. ~utils/mdc/samples 의 key 를 확인하세요.`)
  return s.md
}


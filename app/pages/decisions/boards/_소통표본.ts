/**
 * 소통 판(`fresh.vue`)이 보는 **표본** — 공지·Q&A·소식 세 게시판과 공지 글 하나.
 *
 * ## 왜 실제 모델을 안 읽나
 *
 * 밖에 내보이는 판이라 로그인·권한·로컬 DB 상태에 판이 흔들리면 안 된다. 값은 손으로 박는다.
 * 모양은 지금 실코드(`BoardRow`)보다 **한 발 앞**이다 — 이 판이 묻는 게 「글이 무엇을 가지면 목록이
 * 달라지나」라서, 실코드에 없는 칸(`구분`·`is고정`·`답`·`사진`)을 표본이 먼저 갖는다.
 *
 * - `구분` 은 **데이터**다. 지금 실화면은 제목 앞 `[모집]` 대괄호 글자로 흉내 낸다.
 * - 작성자는 공지·소식에서 뺐다 — 늘 운영진 한 사람이라 열 하나를 통째로 먹었다. Q&A 만 묻는 사람이 뜻이 있다.
 * - 사진 파일은 리포에 없다 — `사진` 은 **색 두 개**다. 판이 파스텔 면으로 칠해 사진의 무게만 본다.
 * - 날짜는 오늘(2026-09-14)을 기준으로 박았다. `is새글` 도 손으로 적는다(사흘 안).
 */


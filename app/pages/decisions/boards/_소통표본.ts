/**
 * 파스텔은 `--ui-bg` 에 섞는다. 섞는 양에 `--파스텔`(라이트 1 · 다크 0.3, 판 뿌리에 적음)을 곱한다 —
 * 다크 바탕에 파스텔을 라이트만큼 섞으면 흙빛 회색이 된다(로그인 창 판에서 실측).
 */
export const 파스텔 = (색: string, 양 = 55) => `color-mix(in oklab, ${색} calc(${양}% * var(--파스텔, 1)), var(--ui-bg))`

/**
 * 사진 자리 — 색 둘로 구름 면을 칠한다. 섞는 양은 `--파스텔` 이 아니라 `--사진`(라이트 1 · 다크 0.6)을 곱한다 —
 * 사진은 다크에서도 사진이라, 0.3 으로 줄이면 흙탕 회색 판이 된다(실측).
 */
const 사진섞기 = (색: string, 양: number) => `color-mix(in oklab, ${색} calc(${양}% * var(--사진, 1)), var(--ui-bg))`
export const 사진칠 = ([가, 나]: readonly [string, string]) => [
  `radial-gradient(70% 90% at 20% 15%, ${사진섞기(가, 95)}, transparent 70%)`,
  `radial-gradient(70% 90% at 85% 90%, ${사진섞기(나, 95)}, transparent 70%)`,
  /** 빛 한 점은 바탕이 아니라 투명에 섞는다 — `--ui-bg` 에 섞으면 다크에서 검은 구멍이 된다(실측). */
  `radial-gradient(40% 50% at 70% 25%, color-mix(in oklab, #FFFFFF calc(55% * var(--사진, 1)), transparent), transparent 70%)`,
  사진섞기(가, 45)
].join(', ')


/**
 * 껍데기가 **화면 밖에 더 먹는 크기**. 판이 배율을 고를 때 먼저 뺀다 — 안 빼면 껍데기만큼
 * 칸을 넘는다. `껍데기틀s` 에서 더해 내므로 치수를 고치면 여기도 같이 움직인다.
 *
 * **눕히면 몫도 같이 눕는다.** 껍데기는 화면이 아니라 **몸통**이라, 기기를 90° 돌리면
 * 위 테두리가 왼쪽으로 가고 옆 테두리가 위아래로 간다 — 폰은 위·아래(10+12)와 옆(8+8)이
 * 서로 달라서, 안 돌리면 배율 계산이 몇 화소 어긋난다.
 * 받침·목·발을 든 것(랩탑·모니터)은 애초에 안 눕는다(`i기기틀.회전`).
 */
export const 껍데기몫 = (종류: i껍데기, 눕는가 = false) => {
  const 틀 = 껍데기틀s[종류]
  const 짧은쪽 = 틀.옆 * 2 + (틀.옆버튼 ? 4 : 0)
  const 긴쪽 = 틀.위 + 틀.아래
  return 눕는가
    ? { 폭: 긴쪽, 높이: 짧은쪽 }
    : {
        폭: 짧은쪽 + (틀.받침 ? 틀.받침.내밀기 * 2 : 0),
        높이: 긴쪽
          + (틀.받침?.높이 ?? 0)
          + (틀.목?.높이 ?? 0)
          + (틀.발?.높이 ?? 0)
      }
}


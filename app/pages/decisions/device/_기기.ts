import { useBreakpoints, useMediaQuery } from '@vueuse/core'
import { computed, onMounted, ref } from 'vue'

export type i기기 = '모바일' | '태블릿' | 'PC'

/** 각 단계가 **시작되는** 폭. 모바일은 0 부터라 여기 안 적는다. */
export const 기기경계 = { 태블릿: 768, PC: 1024 } as const

/** 좁은 쪽부터. 화면에 단계를 늘어놓을 때 이 차례를 쓴다. */
export const 기기s = ['모바일', '태블릿', 'PC'] as const satisfies readonly i기기[]

/** 폭 하나 → 단계 하나. 반응형 밖(표·계산)에서도 같은 답이 나와야 해서 순수 함수로 뺐다. */
export const 기기of = (폭: number): i기기 =>
  폭 >= 기기경계.PC ? 'PC' : 폭 >= 기기경계.태블릿 ? '태블릿' : '모바일'

export const use기기 = () => {
  const bp = useBreakpoints(기기경계)
  const isPC = bp.greaterOrEqual('PC')
  const is태블릿_이상 = bp.greaterOrEqual('태블릿')

  const 기기 = computed<i기기>(() =>
    isPC.value ? 'PC' : is태블릿_이상.value ? '태블릿' : '모바일')

  return {
    기기,
    is모바일: computed(() => 기기.value === '모바일'),
    is태블릿: computed(() => 기기.value === '태블릿'),
    isPC,
    /** 「분할이 성립하는가」 — 목록5·카드s 가 볼 값. 태블릿과 PC 를 같이 묶는다. */
    is태블릿_이상
  }
}


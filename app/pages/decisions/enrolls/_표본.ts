/** 내가 신청한 신청받기인가. 목록 카드·행이 왼쪽 선 하나로 갈라 놓는 그 값. */
export const is내신청 = (id: number) => 표본신청s.some(신청 => 신청.신청받기id === id)

/** 마감 배지에 적히는 말. `null` 은 상시라 배지가 안 붙는다. */
export const 마감라벨 = (남은날: number | null) =>
  (남은날 === null ? '상시' : 남은날 === 0 ? '오늘 마감' : `D-${남은날}`)

/** 남은 자리. 정원이 없으면 `null` — 0(정원 마감)과 「제한 없음」은 다른 말이라 섞으면 안 된다. */
export const 남은자리 = (신청받기: i표본신청받기) =>
  (신청받기.정원 > 0 ? Math.max(0, 신청받기.정원 - 신청받기.신청수) : null)

export const 요금라벨 = (요금: number) => (요금 ? `${요금.toLocaleString('ko-KR')}원` : '무료')

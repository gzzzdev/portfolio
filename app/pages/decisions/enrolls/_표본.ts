/**
 * 신청 비교판 둘(`list`·`detail`)이 같이 보는 **표본**.
 *
 * ## 왜 실제 모델을 안 읽나
 *
 * `do신청세트읽기()` 는 로그인·권한을 타고, 로컬 DB 상태에 따라 목록이 통째로 비기도 한다.
 * 판이 그것 때문에 안 서면 **판을 못 읽는 게 아니라 판이 거짓말을 한다** — 「카드가 휑하다」가
 * 디자인 탓인지 데이터 탓인지 구별이 안 된다. 그래서 값을 손으로 박아 둔다.
 *
 * 대신 값의 **모양**은 실제 모델을 따랐다(`model신청받기` 의 신청수·정원·남은날·is무료).
 * 아이콘·라벨은 `enrolls/types.ts` 의 `i신청받기대상이름표s` 를 그대로 옮겨 적은 것이라,
 * 그쪽이 바뀌면 여기도 어긋난다 — 옮길 때 지워질 판이라 import 하지 않고 베껴 뒀다.
 *
 * 네 안이 **같은 일곱 건**을 그린다. 판마다 데이터가 다르면 무엇 때문에 달라 보이는지 못 가른다.
 */


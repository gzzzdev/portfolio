/**
 * 관례를 프롬프트 한 덩이로 편다.
 *
 * 자리를 `x·y·w×h` 로만 적고 이름과 쓰임을 붙이는 것은, 숫자만으로는 모델이 그 자리를
 * **왜** 지켜야 하는지 몰라 종이가 좁아지면 제일 먼저 버리기 때문이다.
 */
export function 표식관례줄(용도: i용도): string {
  const 목록 = 표식관례s[용도]
  if (!목록.length) return '없음'
  return `\n${목록
    .map((c) => {
      const r = c.자리
      const 설정 = [
        c.설정?.회전 != null && c.설정.회전 !== 0 ? `회전 ${c.설정.회전}` : '',
        c.설정?.불투명도 != null && c.설정.불투명도 !== 1 ? `불투명도 ${c.설정.불투명도}` : '',
        c.설정?.합성 === '곱하기' ? '합성 곱하기' : '',
        c.설정?.맞춤 ? `맞춤 ${c.설정.맞춤}` : ''
      ].filter(Boolean).join(', ')
      const 머리 = [
        `x ${r.x} y ${r.y} ${r.w}×${r.h}`,
        설정,
        c.꼬리표 ? `꼬리표 '${c.꼬리표}'` : '',
        c.겹침허용 ? '글자와 겹쳐도 된다' : ''
      ].filter(Boolean).join(' · ')
      return `  - ${c.이름} — ${머리}\n    ${c.쓰임}`
    })
    .join('\n')}`
}


/**
 * 판형 관례 — **이 종이는 어디에 무엇이 앉는가.**
 *
 * 증서에 직인은 오른쪽 아래에 찍히고, 워터마크는 본문 한가운데에 옅게 깔리고, 명함의 로고는
 * 왼쪽 위에 선다. 아무도 그렇게 하자고 정한 적이 없는데 전부 그렇게 한다 — 그게 관례다.
 * 이 파일은 그 관례를 적어 두고, `AI채우기.ts` 의 세 지시문이 각자 제 몫만 꺼내 쓴다.
 *
 * **왜 지침이 아니라 여기인가.** 지침(`표식지침` · `글자지침`)은 용도와 무관한 규칙이다 —
 * 좌표는 %, 여백은 6%, 어휘는 목록 안에서. 그 문장에 "증서의 직인은 우하단"을 섞으면
 * 명함을 짤 때도 그 말을 읽는다. 용도마다 갈리는 것은 전부 이 파일로 모은다
 * (`생성지시문.ts` 의 `구도지시` 가 배경 쪽에서 이미 같은 자리를 지키고 있다).
 *
 * **왜 좌표까지 적는가.** "위쪽에 놓아라"로는 매번 다른 종이가 나온다. 판형이 굳어 있다는 것은
 * 자리가 굳어 있다는 뜻이고, 굳은 자리는 숫자로 적는 편이 짧고 정확하다. 다만 이건 **초안의
 * 출발점**이지 규격이 아니다 — 지시문이 "특별한 이유가 없으면 이대로, 글자와 부딪히면 옮겨라"
 * 라고 이르고, 나온 뒤에는 캔버스에서 손으로 끈다.
 *
 * **폐기된 스킨 층과 다른 점이 그것이다.** 저쪽은 좌표를 코드가 들고 사람이 못 고쳤다
 * (`designs/index.ts` 머리말). 여기 숫자는 코드가 쥔 좌표가 아니라 **모델에게 건네는 참고값**이고,
 * 모델이 종이 비율과 이미 놓인 글자를 보고 옮긴 결과가 평범한 `i표식`·`i글자` 로 나온다.
 *
 * 좌표는 그 용도가 대개 쓰는 규격 기준이다 (증서 A4 세로 · 포스터 A3 세로 · 명함 90×50 가로 ·
 * 회원증 세로 카드). 규격이 달라지면 모델이 비례로 옮긴다.
 */


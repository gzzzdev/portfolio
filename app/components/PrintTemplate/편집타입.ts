/**
 * 편집기만 아는 상태. **저장되지 않는 것들이다.**
 *
 * 디자인틀의 모양(`~models/test2/designs/디자인틀`)과 갈라 둔 이유는 하나다 — 이 둘은 표에 안 앉는다.
 * 무엇을 잡고 있는지도, 글자가 몇 줄로 접혔는지도 화면을 닫으면 없어지는 것이고,
 * 그걸 모델 타입에 끼워 두면 저장 페이로드에 낄 자리가 있는 것처럼 보인다.
 */

import type { InjectionKey, Ref } from 'vue'

/**
 * 캔버스가 실제로 그려 본 결과. **추정하지 않는다** —
 * 한 줄에 몇 글자가 들어가는지는 글자 수로 셈할 수 없다. 한글은 1em 정사각이지만
 * 라틴은 `i` 0.28em ~ `W` 0.9em 이고, 줄바꿈 규칙도 다르다 (한글은 아무 데서나,
 * 라틴은 공백에서만 — 그래서 긴 이메일은 접히는 대신 잘린다). 서체 12종의 폭도 제각각이고
 * 합성 볼드는 폭을 더 늘린다. 편집기에는 실물이 이미 DOM 에 있으므로 그걸 잰다.
 * (같은 이유로 `m/Fit.vue` 도 가로에서는 실측 이분탐색을 쓴다)
 */
export interface i글자실측 {
  /** 실제로 접힌 줄 수 (세로쓰기면 열 수) */
  줄수: number
  /** 글자가 상자 밖으로 나갔다 — 캔버스는 `overflow-hidden` 이라 조용히 잘린다 */
  넘침: boolean
}

/** 캔버스가 채우고 패널이 읽는다. 둘은 형제라 프롭으로 흘리면 중간(`패널.vue`)이 남의 짐을 진다 */
export const 글자실측키 = Symbol('글자실측') as InjectionKey<Ref<Record<string, i글자실측>>>

/**
 * 캔버스에서 지금 잡고 있는 대상. 편집 패널이 무엇을 보여줄지 정한다.
 *
 * `면` 을 반드시 들고 다닌다 — 양면 인쇄물은 앞뒤가 **동시에** 보이므로
 * "지금 몇 면을 편집 중인가"라는 별도 상태가 없다. 잡은 것이 곧 그 면이다.
 * (모드를 따로 두면 '뒷면 보는 중인데 앞면 글자가 선택된' 상태가 생긴다)
 */
export type i선택
  = | { 면: number, 레이어: '배경' }
    | { 면: number, 레이어: '표식', id: string }
    | { 면: number, 레이어: '글자', id: string }
    | null

/** 사각형을 갖는 선택 — 즉 캔버스가 테두리·손잡이를 그려 줄 수 있는 것 */
export type i상자선택 = Extract<NonNullable<i선택>, { id: string }>

/**
 * 이 선택이 사각형을 갖는가. 캔버스는 이걸 세 군데(선택 테두리·호버 이름표·Tab 순회)에서 묻는다.
 *
 * 지금은 면 전체에 걸리는 레이어가 배경뿐이라 `레이어 !== '배경'` 한 줄과 같다. 그래도 함수로
 * 두는 이유는 테두리 때 겪었기 때문이다 — 그런 레이어가 하나 늘자 세 군데를 다 고쳐야 했다.
 */
export const is상자선택 = (s: i선택): s is i상자선택 =>
  !!s && s.레이어 !== '배경'

/**
 * 표식 배치 스키마.
 *
 * **`채움` 이 있으면 색판이다.** `종류` 를 따로 두지 않는 것은 저장 모델과 같은 이유다
 * (`i표식` 머리말) — 렌더에는 아무 차이가 없으면서 "리본인데 곱하기로 놓았다"를 틀렸다고
 * 말할 근거만 생긴다. 여기서도 갈래는 값이 말한다.
 *
 * `묘사` 는 그림일 때만 뜻이 있다. 색판에 문장을 달아도 뽑을 것이 없다.
 *
 * `보관` 은 보관함 목록의 번호(1부터)다. 링크를 직접 내게 하지 않는 이유: 모델이 주소를 지어내면
 * 그게 그림 없는 상자와 구별되지 않는다. 번호는 범위 밖이면 그냥 버리면 된다(`표식펴기`).
 *
 * **`'없음'` 이 든 문자열 enum 이고 `required` 다.** 처음엔 선택 가능한 `number` 였는데, 모델이
 * 그 칸을 통째로 빼고 답했다 — 보관함에 다섯 개가 실려 갔는데도 종이에는 점선 원만 섰다.
 * 빼도 되는 칸은 빠진다. 그래서 **안 고르는 것도 고르게** 만들었다: 상자마다 번호나 '없음'
 * 둘 중 하나를 반드시 적어야 하니, 목록을 한 번은 보고 지나가게 된다.
 * (`planner.ts` 의 행동 enum 과 같은 수법이다 — 열린 칸보다 닫힌 갈래가 지켜진다)
 */
function 표식스키마(용도: i용도, 보관수: number) {
  const 이미지s = 용도정의s[용도].이미지s
  const properties: Record<string, unknown> = {
    묘사: { type: 'string' },
    채움: { type: 'string' },
    x: { type: 'number' },
    y: { type: 'number' },
    w: { type: 'number' },
    h: { type: 'number' },
    회전: { type: 'number' },
    불투명도: { type: 'number' },
    합성: { type: 'string', enum: [...표식합성s] },
    맞춤: { type: 'string', enum: [...표식맞춤s] }
  }
  // 이 용도가 요구하는 이미지 자리가 하나도 없으면 속성 자체를 만들지 않는다 —
  // 없는 자리를 지목할 길이 사라진다 (`planner.ts` 의 행동 enum 과 같은 규칙)
  if (이미지s.length) properties.꼬리표 = { type: 'string', enum: [...이미지s] }
  // 보관함이 비었으면 마찬가지로 속성을 만들지 않는다 — 고를 것이 없는데 칸만 열어 두면
  // 모델은 아무 값이나 적고, 우리는 그걸 매번 버린다
  const 있음 = 보관수 > 0
  if (있음) {
    properties.보관 = {
      type: 'string',
      enum: ['없음', ...Array.from({ length: 보관수 }, (_, i) => String(i + 1))]
    }
  }

  return {
    type: 'object',
    properties: {
      상자s: {
        type: 'array',
        items: {
          type: 'object',
          properties,
          // 좌표와 함께 `보관` 도 필수다. 이 한 줄이 없으면 모델이 그 칸을 빼고 답한다
          required: 있음 ? ['x', 'y', 'w', 'h', '보관'] : ['x', 'y', 'w', 'h']
        }
      }
    },
    required: ['상자s']
  }
}


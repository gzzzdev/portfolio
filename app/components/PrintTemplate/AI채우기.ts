const 숫자 = (v: unknown, 기본: number) => (typeof v === 'number' && Number.isFinite(v) ? v : 기본)
const 가둠 = (v: number, 최소: number, 최대: number) => Math.min(최대, Math.max(최소, v))

/**
 * 모델이 낸 사각형을 종이 안으로 들인다.
 *
 * 넘친 값을 버리지 않고 **가두는** 이유: 좌표 하나가 101이라고 상자를 통째로 버리면 필수 자리가
 * 조용히 사라진다. 종이 가장자리에 붙어 서 있는 상자는 사람이 보고 끌면 되지만, 없는 상자는
 * 없다는 것조차 보이지 않는다.
 */
function rect가둠(r: Record<string, unknown>, 기본: { x: number, y: number, w: number, h: number }) {
  const w = 가둠(숫자(r.w, 기본.w), 2, 100)
  const h = 가둠(숫자(r.h, 기본.h), 2, 100)
  return {
    x: 가둠(숫자(r.x, 기본.x), 0, 100 - w),
    y: 가둠(숫자(r.y, 기본.y), 0, 100 - h),
    w,
    h
  }
}

/** 닫아 둔 어휘 밖의 값은 **말없이 버리고 기본값을 남긴다** — 없는 서체 이름이 저장되면 화면에 아무 일도 안 일어난다 */
const 골라담기 = <T extends string>(v: unknown, 목록: readonly T[], 기본: T): T =>
  (목록 as readonly string[]).includes(v as string) ? (v as T) : 기본

/**
 * 사람이 이 초안에 건 한마디.
 *
 * **관례보다 위에 둔다.** 관례는 이 판형이 대개 어떻게 생겼는지고, 이 한 줄은 이 사람이 지금
 * 무엇을 원하는지다 — 부딪히면 뒤가 이긴다. 그러라고 있는 칸이다.
 *
 * 자유도를 난수로 주지 않는 이유이기도 하다. 매번 다르게 나오는 것은 자유가 아니라 도박이라
 * (같은 종이를 두 번 뽑아 더 나빠지면 되돌릴 길이 없다), 갈래를 사람이 대는 편이 낫다.
 * 배경 묘사가 처음부터 `요청` 을 받고 있었고(`AI배경묘사`), 이 둘만 그 칸이 없었다.
 */
const 요청줄 = (요청: string) =>
  (요청.trim() ? `\n[사용자 요청 — 관례와 부딪히면 이쪽이 이긴다] ${요청.trim()}` : '')

/** 종이의 생김새를 한 줄로. 세 지시문이 다 같은 문장으로 종이를 말해야 결과가 갈리지 않는다 */
const 종이줄 = (규격: i규격) => {
  const 비 = 규격.폭mm / 규격.높이mm
  const 방향 = 비 > 1.02 ? '가로형' : 비 < 0.98 ? '세로형' : '정사각'
  return `${규격.이름} ${규격.폭mm}×${규격.높이mm}mm (${방향}, 폭/높이 = ${비.toFixed(2)})`
}

/** 응답에서 배열 하나를 꺼낸다. 스키마로 닫아 뒀어도 빈 몸이 오는 날이 있다 */
function 목록꺼내기(응답: unknown, 키: string): Record<string, unknown>[] {
  const v = (응답 as Record<string, unknown> | null)?.[키]
  return Array.isArray(v) ? (v as Record<string, unknown>[]) : []
}


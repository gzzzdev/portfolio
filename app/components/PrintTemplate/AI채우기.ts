/**
 * 단계별 **AI 초안** — 패널의 한 단계를 AI가 먼저 앉혀 본다.
 *
 * 버튼은 '채우기'가 아니라 '초안'이다. 채워 준다고 하면 다 된 것을 받는 줄 알고, 그러면
 * 사람은 결과를 고칠 것으로 보지 않는다. 여기서 나오는 것은 처음부터 고쳐질 것이다
 * (파일 이름은 그 시절 것인데, 부르는 자리가 여럿이라 그대로 둔다).
 *
 * 그림을 뽑는 문장(`생성지시문.ts`)의 형제다. 저장되는 값이 아니라 그 값을 만들어 내는
 * 문장이라는 점이 같고, 그래서 모델(`~models/test2/designs/디자인틀`)이 아니라 편집기가 든다.
 * 디자인틀 한 벌을 종이에 앉히는 데는 이 파일도 하나도 필요 없다.
 *
 * **이건 폐기된 스킨 층의 재림이 아니다.** 저쪽은 좌표를 코드가 들고 AI가 색·서체만 갈아
 * 끼우는 구조였다 — "이름을 조금 왼쪽으로"가 코드 수정이었고, 그래서 사람이 손댈 수 없어
 * 폐기했다(`designs/index.ts` 머리말). 여기서 AI가 내는 것은 **사람이 캔버스에서 고치는 것과
 * 같은 `i글자`·`i표식`** 이다. 나온 순간부터 그냥 상자라, 끌면 끌리고 지우면 지워진다.
 * AI 가 초안을 앉히고 최종권은 캔버스가 갖는다.
 *
 * **한 단계씩만 한다.** 배경 → 표식 → 글자를 한 번에 뱉게 하지 않는 이유가 셋이다.
 *   1. 뒤 단계가 앞 결과를 재료로 쓴다 — 글자 배치는 이미 놓인 표식을 피해야 하고,
 *      배경이 먹빛인지 아이보리인지를 알아야 글자색을 고를 수 있다.
 *   2. 값이 단계마다 다르다. 그림 생성은 느리고 비싸고, 배치는 문자열 한 번이다.
 *      묶어 두면 글자 한 줄을 다시 뽑으려고 그림값을 또 낸다.
 *   3. 사람이 끼어드는 축이 이미 그것이다 — 패널 탭이 곧 이 단계들이라
 *      "표식만 다시"가 그 자리에서 그대로 된다.
 *
 * **그림은 여기서 뽑지 않는다. 다만 있는 것 중에서는 고른다.** 표식 배치는 새 그림을 생성하지
 * 않지만, 보관함에 이미 든 표식은 목록으로 보여 주고 모델이 번호로 지목하게 한다 — 지목한 상자는
 * `url` 이 채워진 채로 나오고, 못 고른 상자만 빈 채로 남아 사람이 고르거나 뽑는다.
 * 초안이 자리와 문장만 내고 종이가 온통 점선 원이면, 사람은 그 초안이 맞는지 볼 수가 없다.
 * 값이 드는 것은 생성이지 고르기가 아니라, 이 한 걸음은 문자열 한 번 안에서 끝난다.
 * 색판(`i표식.채움`)만은 그림이 아니라 색이라 여기서 완성된다.
 *
 * **코드가 지는 몫이 따로 있다.** AI 가 내는 것은 값뿐이고, id 발급·기본값·좌표 가둠·예시
 * 채우기는 전부 아래 `펴기` 함수들이 한다. 그래야 모델이 칸 하나를 빠뜨려도 상자가 성립하고,
 * 100을 넘는 좌표가 종이 밖으로 나가지 않는다.
 */


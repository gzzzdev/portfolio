/**
 * 글자 배치 스키마.
 *
 * **꼬리표를 그 용도의 어휘로 닫는 것이 핵심이다**(`planner.ts` 의 조건 enum 과 같은 수법).
 * 자유 문자열로 두면 모델이 `수령인명` 처럼 그럴듯한 이름을 지어내고, 그 상자는 발급할 때
 * 영영 비어 있는다 — 값을 대는 쪽(`model회원.디자인틀주입`)이 모르는 이름이라서다.
 * 사람이 손으로 치는 칸은 자유 문자열 그대로다(`패널글자.vue`); 막는 것이 아니라
 * 어긋난 이름을 지어낼 길을 안 주는 것뿐이다.
 *
 * `꼬리표` 를 required 에 넣지 않는 이유: **비어 있음이 곧 고정문구다**(`i글자.꼬리표`).
 * 빈 문자열을 enum 에 끼우면 "없음"과 "빈 이름"이 두 값이 되어 같은 뜻이 둘로 갈린다.
 */
function 글자스키마(용도: i용도) {
  return {
    type: 'object',
    properties: {
      상자s: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            꼬리표: { type: 'string', enum: 용도정의s[용도].변수s.map(v => v.키) },
            내용: { type: 'string' },
            x: { type: 'number' },
            y: { type: 'number' },
            w: { type: 'number' },
            h: { type: 'number' },
            크기: { type: 'number' },
            색: { type: 'string' },
            서체: { type: 'string', enum: [...틀서체s] },
            굵기: { type: 'string', enum: [...굵기s] },
            정렬: { type: 'string', enum: [...정렬s] },
            세로정렬: { type: 'string', enum: [...세로정렬s] },
            세로쓰기: { type: 'boolean' },
            줄간격: { type: 'number' }
          },
          required: ['x', 'y', 'w', 'h', '크기', '색', '서체']
        }
      }
    },
    required: ['상자s']
  }
}


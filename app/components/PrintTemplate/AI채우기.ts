/**
 * 상자를 **한 줄은 들어갈 높이**로 키운다.
 *
 * `크기` 는 종이 **폭** 대비, 상자 높이는 **높이** 대비라 축이 다르다. A4 세로에서 크기 12 짜리
 * 제목에 h 8 을 주면 종이에서는 글자가 잘리거나(캔버스는 빨간 테두리로 표시한다) 그 아래로
 * 줄어 찍힌다 — 어느 쪽이든 모델이 고른 크기가 종이에 나타나지 않는다.
 * 지침에 환산식을 적어 뒀는데도 제목 상자만은 계속 작게 나왔다 (2026-09-02, 3회 모두).
 *
 * **크기를 낮추지 않고 상자를 키우는 이유**: 낮추면 위계가 무너진다. 제목이 제목처럼 보이라고
 * 12 를 고른 것이지, 8 이 좋아서가 아니다. 키우는 방향도 아래가 아니라 **가운데 기준 양쪽**이다 —
 * 아래로만 늘리면 다음 상자를 밟는다.
 *
 * 여러 줄 상자는 손대지 않는다. 줄 수를 여기서 알 길이 없고, 애초에 여러 줄짜리는 모델이
 * 넉넉히 잡아 온다 — 이 함수가 보장하는 것은 **한 줄이 들어갈 바닥**뿐이다.
 */

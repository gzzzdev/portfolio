/**
 * 디자인틀을 열고 · 저장하고 · 되돌리고 · 새로 만들고 · 복제하고 · 지우는 일.
 *
 * **컴포넌트 둘이 나눠 쓴다.** 가르는 선은 "목록이 달라지는가"다.
 *   · 디자인틀목록 패널 (`목록.vue`) — **목록**을 다룬다. 새로 만들기 · 열기 · 복제 · 지우기.
 *   · 디자인틀바 (`편집바.vue`, 캔버스 위) — **열어 둔 디자인틀**을 다룬다. 저장 · 되돌리기, 그 둘뿐.
 *
 * 한때 여기 '문서'라는 층이 하나 더 있었다 — 디자인틀에서 뽑혀 나와 따로 사는 한 장. 그 층은
 * 실물이 없었고(저장하는 코드가 디자인틀 표 하나뿐이었다), 그런데도 이름을 두 벌 들어서
 * 캔버스 위엔 `새 등급증_1`, 목록엔 `등급증_1` 이 따로 떴다. 디자인틀 자체를 고치는 중에
 * 디자인틀바가 `등급증_1 에서 고침` 이라고 적던 것도 같은 뿌리다. 지금은 캔버스에 열려 있는
 * 것이 곧 그 디자인틀이고, 이름도 id 도 하나다 (`i틀` 머리말).
 *
 * 그래서 저장이 갈래를 하나 갖는다 — `id` 가 비었으면 처음 저장(POST), 있으면 그 행에
 * 쓰기(PUT). 화면에는 둘 다 '저장' 하나로 보인다. 사람에게는 같은 일이라서다.
 *
 * **표를 직접 만지지 않는다.** 목록·저장·삭제는 `model디자인틀` 이 지고, 이 파일은 그 위에서
 * "지금 캔버스에 있는 것을 잃는가"만 판단한다 — 한때 여기 아래에 `_저장소.ts` 가 있었고
 * `$fetch` 를 직접 쳤다. 같은 표를 두 경로로 읽으면 방금 저장한 행이 목록에서 어긋난다.
 *
 * 확인창도 여기 있다. "무엇을 잃는가"를 아는 것이 배치를 갈아엎는 이 함수들이라, 부르는
 * 쪽마다 다시 물으면 문구가 갈라진다. 묻는 것과 안 묻는 것이 갈리는 기준은 하나다 —
 * **지금 캔버스에 있는 것을 잃는가.** 저장·복제는 안 묻고, 열기·되돌리기·새로 만들기는 묻는다.
 *
 * 묻는 말은 "사라집니다"가 아니라 "저장할까요?" 다. 잃는다고 알리기만 하면 사람이 할 수 있는
 * 일이 취소뿐이라 — 창을 닫고, 저장을 누르고, 하려던 걸 다시 누르게 된다. 그 세 번을 그 자리에서
 * 받는다. 그래서 `window.confirm` 이 아니라 `useModalConfirm` 이다. 갈래가 셋이라서다.
 */

import type { Ref } from 'vue'
import { do디자인틀추가, model디자인틀s, 빈디자인틀, type i틀, type model디자인틀 } from '~models/test2'
import type { i선택 } from './편집타입'

export function use디자인틀(틀: Ref<i틀>, 선택: Ref<i선택>) {
  const 디자인틀s = model디자인틀s.getInstance()

  /** 표에 요청이 떠 있는 동안 — 같은 디자인틀을 두 번 저장하거나 지우는 걸 막는다 */
  const 바쁨 = ref(false)

  /**
   * 지금 캔버스에 열려 있는 디자인틀의 **저장된 모습**. 없을 수 있다 —
   * 아직 한 번도 저장하지 않았거나(`id: ''`), 저장했던 행이 지워졌거나.
   */
  const 저장본 = computed<model디자인틀 | null>(() => 디자인틀s.디자인틀찾기(틀.value.id))

  /**
   * 배치의 지문. 상자 id 는 열 때마다 새로 나므로 뺀다 —
   * 남기면 저장본과 항상 달라 보여 "손댔는가" 판정이 늘 참이 된다.
   */
  const 지문 = (f: Pick<i틀, '이름' | '용도' | '규격' | '면s'>) =>
    JSON.stringify([
      f.이름,
      f.용도,
      f.규격,
      f.면s.map(면 => [
        면.라벨,
        면.배경,
        면.글자s.map(({ id: _, ...나머지 }) => 나머지),
        면.표식s.map(({ id: _, ...나머지 }) => 나머지)
      ])
    ])

  /**
   * 저장된 것과 달라졌는가. 이름·용도·규격까지 센다 — 이름을 고치고 저장을 못 누르면
   * 캔버스 위 이름 칸이 목록과 어긋난 채로 남는다.
   *
   * 저장본이 없으면 **무조건 참이다** — 맞대어 볼 것이 없으니 그 배치는 정말로 어디에도 없다.
   *
   * 함수가 아니라 `computed` 인 건 디자인틀바가 읽어서다. 상자를 끌 때마다 다시 도는데,
   * 디자인틀이 상자 여남은 개라 `JSON.stringify` 두 번이 프레임에 얹히지 않는다.
   */
  const 손댐 = computed(() => !저장본.value || 지문(틀.value) !== 지문(저장본.value))

  const 확인창 = useModalConfirm()

  /**
   * 캔버스를 갈아엎기 전에 한 번 묻는다. 손댄 게 없으면 잃을 것도 없으니 조용히 지나간다.
   *
   * 갈래가 셋이다 — **저장하고 계속 / 저장 안 함 / 취소**. 저장을 골랐는데 저장소가 실패하면
   * 진행하지 않는다. 그러면 알림 한 줄만 뜨고 배치가 그대로 날아간다.
   */
  async function 잃어도되나(말: string): Promise<boolean> {
    if (!손댐.value) return true
    const 답 = await 확인창.open({
      title: '저장할까요?',
      message: 말,
      choices: [
        { key: '저장', label: '저장하고 계속', 역할: '강조' },
        { key: '버림', label: '저장 안 함' },
        { key: '취소', label: '취소' }
      ]
    })
    if (답 === '저장') return await 저장()
    return 답 === '버림'
  }

  /* ── 목록 → 캔버스 ───────────────────────────────────────────── */

  /**
   * 목록에서 하나를 연다.
   *
   * 예전엔 여기서 배경 이미지를 살렸다 — 규격이 같으면 지금 쓰던 그림을 새 배치에 얹었다.
   * 문서가 디자인틀과 별개였을 때는 말이 됐지만(내 종이는 내가 들고 다닌다) 지금은 아니다.
   * 명함_1 을 열면서 등급증의 종이를 끌고 들어가면, 저장하는 순간 명함_1 이 그 그림을 갖는다.
   */
  async function 디자인틀열기(행: model디자인틀) {
    if (String(행.stateId) === 틀.value.id) return
    if (!(await 잃어도되나(`${행.이름} 을 엽니다. 지금 디자인틀에 고친 것이 있습니다.`))) return
    틀.value = 행.열기()
    선택.value = { 면: 0, 레이어: '배경' }
  }

  /** 저장된 모습으로 되돌린다 (배치를 망쳤을 때의 탈출구) */
  function 되돌리기() {
    const 행 = 저장본.value
    if (!행) return
    if (!window.confirm(`${행.이름} 을 저장된 모습으로 되돌립니다. 지금 고친 것은 사라집니다.`)) return
    틀.value = 행.열기()
    선택.value = { 면: 0, 레이어: '배경' }
  }

  /** 빈 종이에서 새로 짓는다. 저장은 아직 하지 않는다 — 이름도 배치도 없는 것을 목록에 세울 이유가 없다 */
  async function 새로만들기() {
    if (!(await 잃어도되나('새 디자인틀을 시작합니다. 지금 디자인틀에 고친 것이 있습니다.'))) return
    틀.value = 빈디자인틀()
    선택.value = { 면: 0, 레이어: '배경' }
  }

  /* ── 캔버스 → 목록 ───────────────────────────────────────────── */

  /** 저장소는 네트워크라 실패한다. 조용히 삼키면 "저장했는데 목록에 없다"가 된다 */
  async function 저장하며<T>(일: () => Promise<T>): Promise<T | null> {
    바쁨.value = true
    try {
      return await 일()
    } catch (e) {
      console.error('[디자인틀] 표 쓰기 실패', e)
      window.alert('저장하지 못했습니다. 콘솔을 확인하세요.')
      return null
    } finally {
      바쁨.value = false
    }
  }

  /**
   * 지금 캔버스를 저장한다. **묻지 않는다** — 잃는 것이 없는 방향이라서다.
   *
   * 처음이면 행을 새로 만들고 그 id 를 캔버스에 물린다. 그래야 다음 저장이 같은 행으로 가고,
   * 되돌릴 곳도 생긴다.
   *
   * 갈래를 `틀.id` 가 아니라 `저장본` 으로 가르는 이유: 열어 둔 디자인틀을 목록에서 지우면 id 는
   * 남아 있는데 행이 없다. 그때 PUT 을 보내면 404 로 저장을 통째로 잃는다 — 행이 없으면
   * 새로 만드는 게 맞다.
   *
   * 됐는지를 돌려준다. '저장하고 계속' 을 고른 사람에게 저장 실패는 곧 진행 취소여야 해서다.
   */
  async function 저장(): Promise<boolean> {
    const 행 = 저장본.value
    if (행) {
      // 담기만으로는 표에 안 간다 — 캔버스의 것을 행에 옮겨 담고, 그 행을 저장한다
      행.담기(틀.value)
      return !!(await 저장하며(() => 행.do저장()))
    }
    const 새행 = await 저장하며(() => do디자인틀추가(틀.value))
    if (새행) 틀.value.id = String(새행.stateId)
    return !!새행
  }

  /**
   * 목록의 디자인틀 하나를 복제한다. 캔버스는 건드리지 않는다 —
   * 열어 보지 않고도 변형을 하나 뜰 수 있어야 `명함_1` 에서 `명함_3` 이 나온다.
   */
  async function 복제(행: model디자인틀) {
    // `열기()` 가 이미 깊게 뜨고 상자 id 까지 새로 낸다 — 사본이 원본과 무엇도 공유하지 않는다
    await 저장하며(() => do디자인틀추가({ ...행.열기(), id: '', 이름: `${행.이름} 사본` }))
  }

  /**
   * 디자인틀을 지운다. 열어 둔 것을 지웠어도 **캔버스는 그대로 남는다** — 규격·용도·면을 스스로
   * 들고 있어서 화면이 빌 이유가 없다. 잃는 것은 되돌릴 곳 하나뿐이고, 디자인틀바가 그렇게 적는다.
   */
  async function 디자인틀지우기(행: model디자인틀) {
    if (!window.confirm(`${행.이름} 을 지웁니다.`)) return
    // 여기서 이미 물었다. `delete(true)`면 BaseModel2가 한 번 더 물어, 같은 일에 확인창이 둘 뜬다.
    await 저장하며(() => 행.delete(false))
  }

  return { 바쁨, 저장본, 손댐, 디자인틀열기, 되돌리기, 새로만들기, 저장, 복제, 디자인틀지우기 }
}

 * 묶음에 맞춰 다시 정의했다** — 묶음마다 자기 무작위가 있고(`m/테마/무작위.vue`), 되돌리기도
 * 묶음 단위다. 이제 상수가 분류를 지배하지 않고 분류가 상수를 정한다.

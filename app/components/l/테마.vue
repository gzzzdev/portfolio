 * 키울수록 그 안쪽 상자가 작아져서(아주 크게에서 73px) 스크롤 축에 손톱만 한 자리가 남는다.
 * 「더보기」는 그 자리를 안 쓴다 — 접힘은 **잘린 그림 + 페이드**, 펼침은 **카드 전부**.
 *
 * **펼치면 pane 이 구르고 축이 밀린다. 그건 괜찮다** — 미는 사람이 사용자 자신이고, 그 순간
 * 하는 일은 「고르기」라 축이 눈앞에 있을 이유가 없다. 접으면 그대로 돌아온다.

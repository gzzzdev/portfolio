/**
 * ## 두 묶음을 가른 기준 — **무엇을 조절하려는 것이냐**
 *
 * 「생김새」는 색·글꼴·모양, 「읽기」는 또렷함·크기다. 그게 전부고, **구현 쪽 사정은 안 본다.**

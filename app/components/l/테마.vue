 * `줄간격` 을 여기서 붙였는데, 그 둘이 `AXIS_GROUPS` 에 없었기 때문이다(무작위가 굴리면
 * 안 되는 값이라서). 지금은 목록이 화면 순서를 말하고 안 굴린다는 사실은 `시력축s` 가
 * 따로 든다 — 그래서 두 묶음이 같은 모양이 됐고, 위 마크업이 한 벌로 접혔다.
 */
const 줄이름s = (묶음: 축묶음) => 묶음축s(묶음).map(n => AXES[n].label)

/**
 * ## 격자는 잘라 두고 「더보기」로 편다 (2026-09-05)
 *
 * 전에는 pane 전체가 굴렀다. 축 열두 줄이 530px 남짓, 격자가 510px 인데 도크 본문은 800px 라
 * **축을 만지려면 격자를 밀어 올려야 했다.** 두 가지가 그때 깨진다.
 *
 * 1. **격자가 스스로를 설명하지 못한다.** 이 배치의 핵심은 카드를 눌렀을 때 「생김새」 줄의
 *    알약들이 미끄러지는 것이 보이는 것인데(`축줄s.vue` 머리말), 그 줄들이 화면 밖에 있으면
 *    약속만 남고 안 지켜진다.
 * 2. **축은 왕복하는 손잡이다.** 돌리고 → 뒤 화면 보고 → 또 돌린다. 그 왕복에 스크롤이 끼면
 *    한 단계가 는다. 반면 격자는 한 번 고르고 끝나는 목록이다.
 *

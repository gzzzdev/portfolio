 * | 보통 | 534px | 239px (두 쌍 남짓) |
 * | 크게 | 601px | 156px |
 * | 아주 크게 | 668px | 73px |
 *
 * 아주 크게에서 두 쌍은 **자리가 없어서** 못 준다 — 축만 668px 인데 판이 801px 다.
 * 거기서 더 짜내려면 축 자체를 줄여야 하고(줄 높이 `h-7` 을 px 로 고정하면 +77px), 그건
 * 「글자를 키워 달라」는 지시와 정면으로 싸우는 일이라 안 한다. 대신 「더보기」가 한 번에 연다.

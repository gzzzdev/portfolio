 *     그래서 이 pane 의 `gap`·`pt`·버튼 높이도 같이 px 다 — 한쪽만 rem 이면 그 줄만 커진다.
 *
 * 「나란히 두 칸」은 안 골랐다: 도크가 28rem(본문 416px)이라 반으로 가르면 208px고,
 * 그러면 축줄이 `쌓기` 로 내려앉아 컨트롤이 오른쪽 한 줄로 맞아떨어지던 게 깨진다.

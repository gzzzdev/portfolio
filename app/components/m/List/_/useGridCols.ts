import type { MaybeRefOrGetter } from 'vue'
import { computed, toValue } from 'vue'
import { useElementSize } from '@vueuse/core'

const GAP = 8
/**
 * 카드 한 장이 먹는 **최소 폭**. 가로카드는 그림 64 + 여백을 빼고 글 칸이 140 은 남아야 한다 —
 * 180 이던 동안은 글 칸이 80px 남짓이라 두 글자 이름도 접혔다(2026-09-11, `_/landscape.vue` 머리말).
 */
const MIN_W: Record<string, number> = { expand: 270, landscape: 240, portrait: 160 }
const MIN_W_DEFAULT = 155

/**
 * **세로카드는 한 열로 그리지 않는다.**
 *
 * 세로카드는 표지가 곧 카드다(`_/portrait.vue`). 그래서 한 열이 되면 표지가 칸 폭을 통째로 먹고,
 * 1:1 아바타 목록은 카드 한 장이 화면 한 판이 된다 — 고르는 화면이 아니라 포스터다.
 * 폴드 겉화면(348px)에서 정확히 이게 났다: 칸 폭 304 는 `MIN_W.portrait`(160) 두 장 + 틈에
 * 24px 모자라서 한 열로 떨어졌고, 8명짜리 목록이 한 화면에 한 명이었다.
 *
 * `MIN_W` 는 **바닥만 있고 천장이 없다.** 가로카드·줄은 폭이 남으면 글이 넓어질 뿐이라 그래도 되지만,
 * 세로카드는 폭이 곧 높이라 남는 폭이 그대로 높이로 간다. 그래서 세로카드에서만, 두 장이 들 폭이면
 * **바닥을 조금 밑돌더라도 두 열로 간다.** 이 값이 그때의 진짜 바닥이다 —
 * 표지 + 이름 한 줄이 읽히는 폭(재서 고른 값이 아니라 두 열 강제를 멈출 자리다).
 */
const MIN_W_세로_2열 = 120

/**
 * 카드 한 장이 먹는 **세로**. 폭 쪽 `MIN_W` 의 짝이고, 같은 이유로 여기 산다 —
 * 이 파일이 그리드 치수의 유일한 출처다.
 *
 * **기기 수가 아니라 카드 제 치수다.** 그래서 화면이 커지든 작아지든 안 움직이고,
 * 카드 디자인을 고칠 때만 같이 고친다. 처음 값(179·155·69)은 폴드 가로(1015×604)에서 첫 장을 잰 것이고
 * (2026-09-09), 카드 뼈대를 다시 짜면서(2026-09-11) **모래밭 `sandbox/theme/list-views` 판에서
 * 칸 폭 560 으로** 다시 쟀다 — 판 머리의 「첫 장」이 이 값이다. 카드를 고치면 거기서 재서 여기 고칠 것.
 */
const MIN_H: Record<string, number> = { landscape: 120 }
const MIN_H_DEFAULT = 64

/**
 * **세로카드는 표지 비율마다 따로 잰다** — 표지가 카드 높이의 대부분이라 비율이 곧 높이다
 * (`BaseModel2.표지비율`). 판에서 각 비율의 표본(역할 16:10 · 회원 1:1 · 캐릭터 3:4)으로 쟀다.
 *
 * 표지는 칸 폭에도 따라 움직인다(3:4 기준 360·2열 291, 560·3열 303, 840·4열 335). 적는 건
 * **분할창 왼쪽 폭(560)** 값이다 — 이 수가 쓰이는 「세로가 좁은가」는 목록5 의 분할 화면에서 걸린다.
 * 모르는 비율이면 가장 흔한 16:10 값으로 본다.
 */
const MIN_H_세로: Record<string, number> = { '16 / 10': 206, '1 / 1': 272, '3 / 4': 303 }

const 카드높이 = (type: string, 표지비율?: string) =>
  type === 'portrait'
    ? MIN_H_세로[표지비율 ?? '16 / 10'] ?? MIN_H_세로['16 / 10']!
    : MIN_H[type] ?? MIN_H_DEFAULT

/**
 * 이 높이의 칸에 그 종류 카드가 **몇 장 드나**. 반 장이 섞여 나온다 —
 * 반쪽이 보이는 것이 「더 있다」는 신호라 정수로 자르면 그 뜻이 사라진다.
 *
 * **칸 높이를 아직 모르면(`0`) `Infinity`** 를 돌려준다. 「모르니까 그대로 둬라」는 뜻이고,
 * 이걸 `0` 으로 두면 첫 그림에서 무조건 강등이 걸려 깜빡인다.
 */
export const 드는장수 = (type: string, 칸높이: number, 표지비율?: string) =>
  칸높이 <= 0 ? Number.POSITIVE_INFINITY : (칸높이 + GAP) / (카드높이(type, 표지비율) + GAP)

/**
 * 목록이 「여럿 중 하나를 고르는 화면」으로 읽히는 최소치.
 *
 * **2장은 나열이고 3장부터 고르는 것이 된다.** 설계 목표는 3.5장(3장 + 다음 장 윗머리)인데,
 * 방아쇠는 3으로 둔다 — 사람이 저장해 둔 보기를 뒤집는 일이라 「3장도 안 될 때」로 좁힌다.
 */
export const 최소장수 = 3

/**
 * 필터를 띠로 접었을 때 그 띠가 먹는 높이. 재서 나온 값이고(2026-09-09) `MIN_H` 와 같은
 * 갈래다 — **부품 제 치수**라 화면 크기와 무관하다.
 */
export const 띠높이 = 32

/**
 * **세로가 좁은가** — 「접을 수 있는 만큼 접고도 최소장수가 안 서나」.
 *
 * `공유높이` 는 **목록 칸과 필터 칸의 합**이다. 목록 칸만 보면 「좁다 → 접는다 → 넓어졌다 →
 * 편다 → 좁다」로 진동한다. 둘은 같은 세로 칸의 형제라 합이 결정에 안 움직이고, 그래서
 * 되먹임이 안 생긴다. 띠높이를 **미리 빼고** 묻는 것도 같은 이유다 — 묻는 것이
 * 「지금 서나」가 아니라 「접고도 안 서나」라야 접는 것이 답이 된다.
 *
 * **부르는 자리는 `목록5.vue` 하나다.** 한동안 모래밭 판이 같이 불렀다 — 판이 제 계산을
 * 따로 들면 두 답이 갈려서였다. 판은 지웠고 규칙만 남았다.
 *
 * 아직 안 재어 봤으면(`0`) **안 좁다**고 답한다 — 첫 그림에서 크롬이 깜빡이지 않게.
 *
 * `표지비율` 은 세로카드일 때만 뜻이 있다 — 3:4 증명사진 목록은 16:10 목록보다 한 장이 1.5배 길어서
 * 같은 칸에서 더 일찍 줄로 내려간다. 그게 맞다: 장수가 안 서는 건 비율과 무관하게 같은 문제다.
 */
export const 좁은높이인가 = (보기type: string, 공유높이: number, 표지비율?: string) =>
  공유높이 > 0 && 드는장수(보기type, 공유높이 - 띠높이, 표지비율) < 최소장수

/**
 * 그리드 치수의 유일한 출처.
 * 열 수를 CSS auto-fill에 맡기면 JS는 몇 열인지 알 수 없어 키보드 이동과 어긋난다.
 * 그래서 auto-fill이 하던 계산을 여기서 하고, 레이아웃도 키보드 이동도 이 값을 쓴다.
 */
export function useGridCols(
  el: MaybeRefOrGetter<HTMLElement | null | undefined>,
  type: MaybeRefOrGetter<string>
) {
  const { width } = useElementSize(el)

  const cols = computed(() => {
    const t = toValue(type)
    if (t === 'row') return 1
    const min = MIN_W[t] ?? MIN_W_DEFAULT
    const n = Math.max(1, Math.floor((width.value + GAP) / (min + GAP)))
    // 아직 안 재어 봤으면(`0`) 그대로 1 — 첫 그림에서 열 수가 튀지 않게
    if (n >= 2 || t !== 'portrait' || width.value <= 0) return n
    // 세로카드 한 열은 카드가 아니라 포스터다 (`MIN_W_세로_2열`)
    return width.value + GAP >= 2 * (MIN_W_세로_2열 + GAP) ? 2 : n
  })

  return {
    cols,
    /** gap도 같은 상수에서 나와야 위 계산이 맞는다 (클래스로 주지 말 것) */
    gridStyle: computed(() => ({
      gap: `${GAP}px`,
      gridTemplateColumns: `repeat(${cols.value}, minmax(0, 1fr))`
    }))
  }
}

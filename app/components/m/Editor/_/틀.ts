/**
 * 편집판의 **액자** — 외곽선 하나와 뜸(그림자 축)뿐이다.
 *
 * ## 왜 이 파일이 생겼나 (2026-09-07)
 *
 * `Input/*` 스물몇 개 중 **본문만 Nuxt UI 입력을 안 감싼다.** 나머지는 `UInput`·`UTextarea`·
 * `USelect`·`UInputNumber`… 를 감싸고, 그중 `input`·`textarea`·`select` 는 재질 축의
 * `VARIANT_COMPONENTS`(`m/테마/재질.ts`)라 **외곽선·면·focus 링이 래퍼에 딸려 온다.**
 * 본문은 tiptap 의 `<EditorContent>` 를 직접 감싸서 그 껍데기가 없다.
 *
 * **아무도 액자를 뺀 적이 없다** — 액자를 공급하던 것이 래퍼였고, 본문만 래퍼를 안 썼을 뿐이다.
 * 그래서 편집기만 혼자 액자 없이 서 있었고, 2026-09-04 쓸이에도 안 걸렸다. 그 쓸이는
 * `bg-white`·`shadow-md` 같은 raw 클래스를 훑어 221곳을 찾은 것인데, **없는 것은 안 훑린다.**
 *
 * 이 파일이 래퍼가 하던 일 중 **액자에 해당하는 몫만** 대신 한다.
 *
 * ## 액자는 선이지 면이 아니다 (2026-09-07 결정)
 *
 * 처음에는 재질 축 한 칸(`ui.textarea.defaultVariants.variant`)을 그대로 물어다 씌웠다.
 * 그러니까 `soft`·`subtle` 에서 **편집판에 음영이 깔렸다.** 한 줄 입력에서는 그 면이 「여기 쓰는
 * 자리」를 뜻하지만, 본문은 화면의 절반을 먹는 판이라 같은 면이 **글 뒤에 깔린 색**이 된다 —
 * 읽기 화면과 픽셀로 같아야 한다는 이 컴포넌트의 기준(`Editor.vue` 머리말의 *"그 밖의 차이가 보이면
 * 버그다"*)에 정면으로 걸린다. **재질 축은 안 탄다.** 액자는 늘 외곽선 하나다.
 *
 * 그래도 손으로 `ring ring-inset ring-accented` 를 적지는 않는다 — 재질 표의 `outline` 칸에서
 * **선만** 뜯어 온다(`prose.ts` 와 같은 규율: 테마를 읽고 다시 안 적는다). Nuxt UI 가 그 칸의
 * 토큰을 바꾸면 액자도 같이 따라간다.
 *
 * 액자에 남는 축은 둘이다 — **반경**(`rounded-md` → `mTheme.css` 의 `--radius-md`)과
 * **뜸**(`.m-층-카드` → `m/테마/그림자.ts`). 손잡이를 돌리면 이 둘이 움직인다.
 *
 * ## 읽기 모드에는 액자가 아예 없다
 *
 * 읽기는 게시판·상세 화면에 **글로** 얹히는 것이라 제 테두리를 가질 이유가 없다 — 액자는 바깥
 * 카드가 이미 지고 있고, 여기 선을 하나 더 그으면 상자 안 상자가 된다.
 * `mTheme.css` 뜸 블록이 이름표를 붙일지 말지의 기준으로 적어둔 문장이 그대로 이 구분이다 —
 * *"글로 읽히느냐 물건으로 얹혔느냐."* 읽기는 **글**, 수정은 **만지는 물건**이다.
 * 그래서 읽기 모드는 액자도 여백도 통째로 비고, 읽기 화면과 픽셀로 같아진다.
 *
 * **둘째 매개변수 이름은 `읽기` 다 — `readonly` 로 두면 안 된다.** Vue 의 `readonly` 가 Nuxt 자동
 * 임포트에 걸려 모듈 맨 위에 `import { readonly } from 'vue'` 가 딸려 온다 (dev 변환 결과에서 실측).
 * 함수 안에서는 매개변수가 가려서 동작은 맞지만, 안 쓰는 임포트가 남고 다음 사람이 헷갈린다.
 *
 * **툴바 줄에도 면을 안 준다.** 크롬을 파임(`bg-muted`)으로 내리는 손이 먼저 갔는데, 면을 안 쓰기로
 * 한 위 결정과 어긋난다. 선 하나면 어느 모드에도 안 걸린다.
 *
 * ## 도구와 글을 가르는 선은 「띠」가 진다 (2026-09-07)
 *
 * 그 선이 한동안 `툴바` 칸의 `border-b` 였다. 지금은 **`띠선`** 이다 — 툴바 줄 아래에 손잡이 띠가
 * 한 장 더 서기 때문이다(`Editor.vue` 머리말 「띠」). 크롬의 마지막 층이 툴바가 아니라 띠라서,
 * 선도 거기로 내려왔다. 툴바에 선을 도로 붙이면 **띠가 선 아래로 밀려나** 글의 일부처럼 보인다.
 *
 * `띠선` 은 **펴진 동안에만 걸린다.** 접히면 크롬이 띠 한 장뿐이라 그 아래 선을 그으면
 * 액자 맨 위에 이유 없는 가로줄이 남는다 — 걷어낸 「빈 띠 + 선」이 그대로 돌아온다.
 * 접힌 띠의 모서리는 `Editor.vue` 가 `rounded-t-md` 로 액자와 맞춘다(hover 면이 삐지는 것만 막는 값이라
 * 액자의 반경과 같은 이름을 쓰면 그만이다).
 */
import textareaTheme from '#build/ui/textarea'

const 재질표 = textareaTheme.variants.variant as Record<string, string>

/**
 * 재질 한 칸에서 **가만히 있을 때의 선만** 남긴다. 버리는 것이 셋이다.
 *
 * - `bg-*` — 위 「액자는 선이지 면이 아니다」. 이걸 버리는 게 이 함수의 요점이다.
 * - `text-*` — 재질 표의 값이 전부 `text-highlighted` 로 시작하는데, 그걸 씌우면 **편집판의
 *   문단이 읽기 화면보다 밝아진다.** 읽기판은 `<article class="m-본문">` 하나뿐이고
 *   (`enrolls/[id].vue`), prose 의 `p` 는 색을 안 적어서(`.nuxt/ui/prose/p.ts` =
 *   `my-5 leading-7 text-pretty`) 주변 색을 물려받기 때문이다. 색을 갖는 건 제목뿐이다.
 * - **앞가지가 붙은 것**(`hover:`·`focus:`·`disabled:`) — 한 줄 입력의 상태 신호다.
 *   문서 판은 **포인터가 늘 그 위에 있어서** hover 가 「누를 수 있다」를 뜻하지 못한다.
 *   (`focus:`·`disabled:` 는 어차피 `div` 에서 안 걸린다.)
 */
function 선만(v: string | undefined): string {
  return (v ?? '')
    .split(/\s+/)
    .filter(t => t && !t.includes(':') && !t.startsWith('text-') && !t.startsWith('bg-'))
    .join(' ')
}

export interface i본문틀 {
  /** 바깥 액자 — 선·모서리·층. 면은 없다. */
  틀: string
  /** 툴바 줄 — 여백만. 아래를 가르는 선은 `띠선` 이 진다. */
  툴바: string
  /** 손잡이 띠가 도구와 글을 가르는 선. **펴진 동안에만** 건다. */
  띠선: string
  /** 글이 서는 자리 — 여백 */
  판: string
}

export function 본문틀(읽기: boolean): i본문틀 {
  if (읽기)
    return { 틀: '', 툴바: '', 띠선: '', 판: '' }

  return {
    // `rounded-md` 는 반경 축을 탄다 (`mTheme.css` 의 `--radius-md: var(--ui-radius-md)`).
    // `.m-층-카드` 는 `--tw-shadow` 로 들어가므로 `outline` 의 `ring` 과 같이 산다
    // (링에게 지는 이야기는 `mTheme.css` 뜸 블록의 경고가 정본).
    틀: `${선만(재질표.outline)} rounded-md m-층-카드`,
    툴바: 'px-3 py-2',
    띠선: 'border-b border-default',
    판: 'px-4 py-3'
  }
}

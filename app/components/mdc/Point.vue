<template>
  <ProseCallout
    color="primary"
    :icon="icon || 'i-lucide-star'"
  >
    <slot mdc-unwrap="p" />
  </ProseCallout>
</template>

<script setup lang="ts">
/**
 * `::point` — **요점.** 본문에서 강조색(`primary`)을 쓰는 **유일한** 블록이다.
 *
 * ## 왜 `note` 에 강조색을 주지 않았나
 *
 * 알림 넷 중 색에 뜻이 없는 건 `note` 하나뿐이라(초록=괜찮음·주황=조심·빨강=위험은 관습),
 * 거기에 강조색을 태우는 게 제일 싸 보인다. 그런데 **`note` 의 뜻이 정반대다** —
 * 사전의 `쓸때` 가 "읽고 지나가도 되는 보충"이고, 강조색이 하는 말은 "여기를 봐라"다.
 * 색이 뜻을 배신하면 그게 곧 꾸미기다(`::note{color="red"}` 를 막은 것과 같은 이유).
 *
 * 실측도 같은 쪽이다 — 샘플 세 편에서 `note` 는 **한 번**, `tip`·`warning`·`caution` 은 각각 두 번
 * 나왔다. 이유가 있으면 뜻이 있는 것을 고르고, `note` 는 남는 자리다.
 * **제일 안 중요한 칸에 브랜드색을 줄 수는 없다.**
 *
 * ## 경계는 뜻이 아니라 빈도다
 *
 * 강조색이 하는 일은 하나다 — "여기를 봐라". 그건 **둘이 되는 순간 없어진다.**
 * 그래서 이 블록의 경계 문장은 옆 블록과의 차이가 아니라 **글 하나에 한 번**이다.
 * 테마 문서의 "색을 갖는 역할은 `강조` 하나뿐, 화면당 0~1개"를 본문에 옮긴 것이다.
 *
 * ## `::box` 를 안 만든 이유
 *
 * "무엇이든 담는 상자"는 경계 문장을 못 적는다. 못 적는다는 건 고를 기준이 없다는 뜻이고,
 * 기준이 없는 블록은 곧 꾸미기 도구가 된다 — 네이버 카페를 피하려던 그것이다.
 * (`::focus` 도 안 썼다. CSS `:focus` 와 헷갈리고, `::card` 는 이미 다른 뜻으로 있다.)
 *
 * ## 만든 것은 색뿐이다
 *
 * `ProseCallout` 을 그대로 쓴다 — 여백·모서리·다크모드·링크 색이 전부 `@nuxt/ui` 것이고,
 * `color="primary"` 는 `--ui-color-primary-*` 를 타므로 **강조색 손잡이를 돌리면 같이 움직인다.**
 * 알림 넷은 안 움직인다(상태색은 `테마/축s.ts` 의 `aliasVars` 가 안 덮어서 축 밖이다).
 * 즉 본문에서 축을 타는 색은 이 한 칸뿐이고, 그게 의도다.
 */
interface Props {
  /** 기본 아이콘 대신 쓸 것(`i-lucide-*`). 대개 생략한다. */
  icon?: string
}
defineProps<Props>()
</script>

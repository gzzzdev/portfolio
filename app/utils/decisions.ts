/**
 * 「이 사이트는 이런 고민 속에 만들어졌습니다」(`/decisions`)의 **정본**.
 *
 * ## 판은 여기 산다 (2026-09-06)
 *
 * 한동안 기록만 여기 두고 비교판은 모래밭(`/sandbox`)에 남겨 링크로 건너갔다. 그게 틀렸다 —
 * **모래밭은 언제든 통째로 지우는 도구인데, 밖에 내보이는 화면이 거기를 가리키고 있었다.**
 * 지우면 증거가 같이 사라지고, 안 지우려고 눈치를 보면 도구가 썩는다. 둘 다 나쁘다.
 *
 * 그래서 수명으로 갈랐다. **두 자리의 차이는 「끝났나」다:**
 *
 * - **모래밭(`/sandbox`) = 아직 기록에 안 올렸다.** 후보를 깔고 값을 물려 본다. 개발자만 본다.
 * - **여기(`app/pages/decisions/*`) = 기록에 올렸다.** 판이 그 물음의 증거물로 이사 오고,
 *   **모래밭에서는 지운다.** 두 벌로 두지 않는다 — 둘이 갈라지는 순간 한쪽이 거짓말을 한다.
 *
 * **기준은 「결론이 났나」가 아니라 「기록에 올랐나」다.** `결론` 이 없어도 「아직 열려 있는
 * 질문」으로 밖에 나가므로, 그 증거물이 지워지는 폴더에 있으면 안 된다
 * (`상자-면`·`게시판-상세` 둘이 지금 그 경우다).
 *
 * 그래서 이 폴더는 밖에 나가는 공개 경로다. **판은 도메인 데이터를 읽지 않는다** —
 * `_표본.ts` 같은 정적 자료로 든다.
 *
 * `판` 경로는 그래도 라우터에 실재할 때만 링크한다 — 판을 지워도 기록은 그대로 서야 한다.
 *
 * ## 무엇을 적나
 *
 * **두 층이다.** 카드에 보이는 `고민`·`요약` 은 처음 보는 사람의 말로, 상세(`/decisions/{키}`)에만
 * 보이는 `놓고본것`·`결론`·`근거`·`반영` 은 만든 사람의 메모 그대로.
 *
 * 메모도 한 줄 요약만. **왜 그 값이 이겼는지 논거 원문은 옮겨 적지 않는다** — `근거` 가 가리키는
 * 코드 옆 머리말이 정본이다. 두 벌이 되는 순간 한쪽이 거짓말을 시작한다 (CLAUDE.md 「테마」).
 *
 * 같은 이유로 **판의 `definePageMeta` 에는 `제목` 만 둔다.** 「무엇을 놓고 봤나」·「어디에
 * 나갔나」는 여기 `놓고본것`·`반영` 이 지므로, 판에 다시 적으면 그게 곧 두 벌이다.
 *
 * `결론` 이 없으면 아직 안 고른 것이고, `/decisions` 에서 「아직 열려 있는 질문」으로 내려간다.
 * 고르고 나면 여기 한 줄을 적는다 — 판에 적는 게 아니다.
 *
 * **고른 것과 나간 것은 다르다.** 판에서 값을 고른 날과 실코드가 그 값이 되는 날 사이에는
 * 대개 시차가 있고, 그 사이에 `결론` 만 보고 「정한 것」에 올리면 화면이 거짓말을 한다
 * (밖에 내보이는 화면이라 더 그렇다). 그 시차를 `is미반영` 이 진다 — 켜져 있으면
 * `/decisions` 에서 「골랐고, 아직 안 넣었다」로 따로 선다.
 */
export interface iDecisionEntry {
  /** 안정된 열쇠. 판을 옮기거나 지워도 안 바뀐다. 상세 주소(`/decisions/{키}`)이기도 하다. */
  키: string
  /**
   * 무엇에 대한 결정인가. `/decisions` 가 이걸로 묶는다 — **설계(데이터·권한)가 화면보다 앞에 선다.**
   * 기록이 전부 화면 결정이던 때, 밖에서 보기엔 「UI 취향 기록」으로 읽혔다(2026-09-15 검토).
   */
  갈래: '설계' | '화면'
  /** 그 갈림길에서 실제로 물은 것. 한 문장. **처음 보는 사람이 읽히는 말로** — 카드 제목이다. */
  고민: string
  /**
   * 카드에 보이는 한 줄. **평범한 말 + 숫자 하나.** 코드 이름·CSS 변수·이 리포 안에서만 통하는 말
   * (「판에서 졌다」·「갈래로 올렸다」…)은 쓰지 않는다 — 그런 말은 `결론` 에 두고 상세에서만 보인다.
   * 카드에 `결론` 을 그대로 올렸더니 한 장을 두세 번 읽어야 했다(2026-09-15 검토).
   * 결론이 없는 기록은 「무엇을 재고 있나」를 적는다.
   */
  요약: string
  /** 후보로 나란히 놓고 본 것들. */
  놓고본것: string
  /** 이긴 값 + 진 안이 왜 졌는지 한 줄. 없으면 아직 고르는 중. */
  결론?: string
  /** 논거 원문이 있는 자리(정본). 판이 아니라 **오래 남는 코드** 를 가리킬 것. */
  근거: string
  /** 그 결정이 실제로 나가 있는 자리. `is미반영` 이면 「지금까지 온 데」를 적는다. */
  반영?: string
  /** 값은 골랐는데 실코드가 아직 옛 판인가. `결론` 이 있을 때만 뜻이 있다. */
  is미반영?: boolean
  /**
   * 비교판. `app/pages/decisions/*` 안을 가리킨다 — **모래밭을 가리키지 말 것**
   * (거기는 지워지는 자리다). 지워지면 링크만 빠지고 기록은 그대로 선다.
   */
  판?: string
}

/**
 * `/decisions` 의 묶음과 상세의 눈썹이 같이 읽는 상태. 판정은 여기 한 곳이다.
 *
 * **이 파일의 export 이름은 ASCII 여야 한다** — `app/utils` auto-import 가 한글 이름이 섞인 import 줄을
 * 못 알아보고 `decisionRecord` 를 한 번 더 주입해 페이지 매크로가 통째로 죽었다(`usePortfolio.ts` 머리말과 같은 사정).
 */
export type DecisionStatus = '정함' | '미반영' | '열림'
export function decisionStatus(기록: iDecisionEntry): DecisionStatus {
  if (!기록.결론) return '열림'
  return 기록.is미반영 ? '미반영' : '정함'
}

/**
 * 판이 라우터에 **실제로** 있나. `matched` 가 비었나만 보면 안 된다 — 상세(`decisions/[key].vue`)가
 * `/decisions/*` 한 칸을 전부 받아서, 지워진 판(`/decisions/nav`)도 상세로 풀려 「있다」가 된다.
 */
export function hasDecisionBoard(기록: iDecisionEntry, router: { resolve: (to: string) => { matched: { name?: unknown }[] } }): boolean {
  if (!기록.판) return false
  const matched = router.resolve(기록.판).matched
  return matched.length > 0 && matched.at(-1)?.name !== 'decisions-key'
}

/** `근거` 의 첫 토막이 파일 경로면 저장소의 그 파일 주소. 「머리말」 같은 꼬리말은 뗀다. */
export function decisionSourceUrl(기록: iDecisionEntry, 저장소: string): string | null {
  const 경로 = 기록.근거.split(' ')[0] ?? ''
  if (!/^(README\.md|(app|_CUSTOM|server)\/.+\.\w+)$/.test(경로)) return null
  return `${저장소}/blob/main/${encodeURI(경로)}`
}

